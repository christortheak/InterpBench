    /// not built for the loaded model is a disabled row naming the model to
    /// load (the historical rule showed nothing until a model was loaded).
    nonisolated public static func localAgentExclusion(
        baseModelID: String, loadedModelID: String?
    ) -> String? {
        guard baseModelID != loadedModelID else { return nil }
        return "built for \(baseModelID) — load it to use"
    }

    /// THE selector-source rule (pure, unit-tested):
    /// - Server workspace: the ACTIVE server's stored agents (all of them —
    ///   one whose base model is missing from the server's inventory is a
    ///   disabled row naming why), PLUS every local agent definition
    ///   (recipes are visible in every workspace) offered as an inline-spec
    ///   entry — disabled with the applicability reasons when the server
    ///   cannot run it. Manually-created agents are local definitions, so
    ///   this is what puts them in the Playground selector.
    /// - Local workspace: local definitions only; one built for a different
    ///   model is a disabled row ("built for X — load it to use"), never
    ///   silently absent.
    nonisolated public static func agentPickerRows(
        workspaceIsServer: Bool,
        serverAgents: [RemoteVariantRecord],
        installedServerModels: [String],
        localDefinitions: [LocalAgentCandidate],
        localLoadedModelID: String?
    ) -> [AgentPickerRow] {
        if workspaceIsServer {
            var rows = serverAgents.map { agent in
                AgentPickerRow(
                    selection: .server(path: agent.path),
                    title: "\(agent.name) · \(agent.baseModelID)",
                    exclusionReason: serverAgentExclusion(
                        baseModelID: agent.baseModelID,
                        installedServerModels: installedServerModels))
            }
            rows.append(
                contentsOf: localDefinitions.map { candidate in
                    AgentPickerRow(
                        selection: .localDefinition(id: candidate.id),
                        title: "\(candidate.name) · local definition (inline)",
                        exclusionReason: candidate.serverBlockReasons.isEmpty
                            ? nil
                            : candidate.serverBlockReasons.joined(separator: "; "))
                })
            return rows
        }
        // Same-named agents get a distinguisher naming what actually
        // differs; a unique name is left alone. Promoting one concept twice
        // in an afternoon is routine, and a timestamp would say which came
        // later without saying why there are two.
        let labels = Dictionary(
            uniqueKeysWithValues: ArtifactDisambiguation.labels(
                localDefinitions.map {
                    .init(
                        id: $0.id, displayName: $0.name, identity: $0.identity,
                        createdAt: $0.createdAt)
                }
            ).map { ($0.id, $0) })
        return localDefinitions.map { candidate in
            AgentPickerRow(
                selection: .localDefinition(id: candidate.id),
                title: labels[candidate.id]?.text ?? candidate.name,
                exclusionReason: localAgentExclusion(
                    baseModelID: candidate.baseModelID,
                    loadedModelID: localLoadedModelID))
        }
    }

