    /// Recenter a slot's layer when its vector changes (mid-network default).
    public func applyDefaultLayer(slotID: UUID) {
        guard let index = slots.firstIndex(where: { $0.id == slotID }) else { return }
        if isServerWorkspace {
            guard let record = serverVectorRecord(for: slots[index]) else { return }
            slots[index].layer = Double(record.layerCount / 2)
            return
        }
        guard let artifact = artifact(for: slots[index]) else { return }
        slots[index].layer = Double(artifact.fixedSteeringLayer ?? artifact.sidecar.layerCount / 2)
    }

    /// The α control's current explanation — units, why this number, which
    /// denominator convention, and (raw mode only) the backfill repair.
    /// Written by `applyDefaultsForSelectedVector`; the view renders it and
    /// computes nothing.
    public private(set) var alphaDefaultDecision: SlotAlphaDefault.Decision?

    /// Everything `SlotAlphaDefault` needs about the slot's artifact, read off
    /// whichever catalog the active workspace uses. `nil` when no vector is
    /// selected or the artifact is not in the catalog.
    public func alphaDefaultFacts(slotID: UUID) -> SlotAlphaDefault.ArtifactFacts? {
        guard let index = slots.firstIndex(where: { $0.id == slotID }),
            let vectorID = slots[index].vectorID
        else { return nil }

        func facts(
            layerCount: Int, fixedLayer: Int?, norms: [Float]?, convention: String?
        ) -> SlotAlphaDefault.ArtifactFacts {
            let layer = fixedLayer ?? max(0, layerCount / 2)
            let recommendation = SlotAlphaDefault.recommendation(
                forVectorArtifactID: vectorID,
                among: fineTuning.variants.map(\.artifact))
            return SlotAlphaDefault.ArtifactFacts(
                artifactID: vectorID,
                layer: layer,
                residualNormAtLayer: norms?[safe: layer],
                residualNormConvention: convention,
                recommendedAlpha: recommendation?.alpha,
                recommendedAlphaInNormUnits: recommendation?.normUnits,
                recommendedFromAgent: recommendation?.agent,
                recommendedPromotedBy: recommendation?.promotedBy)
        }

        if isServerWorkspace {
            guard let record = serverVectorRecord(for: slots[index]) else { return nil }
            return facts(
                layerCount: record.layerCount, fixedLayer: nil,
                norms: record.residualNormPerLayer,
                convention: record.residualNormConvention)
        }
        guard let artifact = artifact(for: slots[index]) else { return nil }
        return facts(
            layerCount: artifact.sidecar.layerCount,
            fixedLayer: artifact.fixedSteeringLayer,
            norms: artifact.sidecar.residualNormPerLayer,
            convention: artifact.sidecar.residualNormConvention)
    }

    /// Apply the artifact-aware defaults after a slot's vector changes: layer,
    /// then α and its UNITS, from `SlotAlphaDefault`.
    ///
    /// This is what replaces the flat `alpha = 2`. The unit mode is a session
    /// property, so it flips only when norm units have become genuinely
    /// unavailable — and when it flips, it says so (`errorMessage`), because a
    /// silent flip means the same numeral is suddenly a different dose.
    public func applyDefaultsForSelectedVector(slotID: UUID) {
        applyDefaultLayer(slotID: slotID)
        guard let index = slots.firstIndex(where: { $0.id == slotID }),
            let facts = alphaDefaultFacts(slotID: slotID)
        else {
            alphaDefaultDecision = nil
            return
        }
        // Ablation rows carry λ, not α: `defaultAblationStrength` governs
        // there and no denominator is ever consulted.
        guard slots[index].mode != .ablate else {
            alphaDefaultDecision = nil
            return
        }
        let decision = SlotAlphaDefault.decide(facts)
        slots[index].alpha = decision.alpha
        alphaDefaultDecision = decision

        if !decision.isNormUnits, alphaInNormUnits, !normUnitsAvailable {
            alphaInNormUnits = false
            errorMessage =
                "α is now in RAW units: '\(facts.artifactID)' stores no "
                + "residual-norm denominator. Repair: \(decision.backfillHint ?? "")"
        }
    }

    // MARK: - Actions

    public func refreshVectors() {
        vectors = VectorCatalog.scan()
        catalog.refreshLocalVectors()  // keep the workspace index in step
        readingProbes = ProbeCatalog.scan()
        refreshNeutralCorpora()
        refreshNeutralPCBases()
        staleVectorIDs = Set(vectors.filter(VectorCatalog.isStale).map(\.id))
        if let selectedProbeID,
            !compatibleReadingProbes.contains(where: { $0.id == selectedProbeID })
        {
            self.selectedProbeID = nil
        }
        if let selectedNeutralPCBasisID,
            !compatibleNeutralPCBases.contains(where: { $0.id == selectedNeutralPCBasisID })
        {
            self.selectedNeutralPCBasisID = nil
        }
        if selectedNeutralPCBasisID == nil,
            let first = compatibleNeutralPCBases.first
        {
            selectedNeutralPCBasisID = first.id
        }
        fineTuning.refresh()
        // Clear the agent selection only when the RECORD is gone (deleted) —
        // a base-model mismatch now renders as a visible disabled row in the
        // Playground picker, so it must not silently drop the selection.
        if let selectedSteeringVariantID,
            !fineTuning.variants.contains(where: { $0.id == selectedSteeringVariantID })
        {
            self.selectedSteeringVariantID = nil
        }
        if let selectedRuntimeAdapterID,
            !compatibleAdapters.contains(where: { $0.id == selectedRuntimeAdapterID })
        {
            self.selectedRuntimeAdapterID = nil
        }
        if selectedRuntimeAdapterID == nil {
            selectedRuntimeAdapterID = compatibleAdapters.first?.id
        }
        if slots.count == 1, slots[0].vectorID == nil,
            let first = compatibleVectors.first
        {
            slots[0].vectorID = first.id
            // Auto-fill is a SELECTION too: it must not leave the flat α
            // default behind on a vector that knows its own strength.
            applyDefaultsForSelectedVector(slotID: slots[0].id)
        }
    }

