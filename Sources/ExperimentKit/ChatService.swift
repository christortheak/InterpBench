            "- Injection enabled: \(steeringEnabled)",
            "- Active vectors: \(activeSlotCount)",
            "- Alpha units: \(alphaInNormUnits ? "residual-norm" : "raw")",
            "- Layer band: \(layerBandWidth)",
            "- Neutral PC removal: \(removeNeutralDirectionsAtSteering)",
        ]
        // Server-generation provenance: a stored variant's path+hash, or the
        // server's `source: "inline"` stamp — an edited chat never claims a
        // stored variant's identity in the exported transcript.
        if let provenance = lastServerVariantProvenance {
            lines.append("- Server variant: \(provenance)")
        }
        if let adapter = selectedRuntimeAdapter {
            lines.append("- Adapter: \(adapter.artifact.name)")
        }
        if let probe = selectedReadingProbe {
            lines.append("- Probe: \(probe.label)")
        }
        let trimmedSystem = systemPrompt.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmedSystem.isEmpty {
            lines.append("- System prompt: \(trimmedSystem)")
        }
        let activeSlots = slots.compactMap { slot -> String? in
            guard slot.enabled,
                let vectorID = slot.vectorID,
                let artifact = vectors.first(where: { $0.id == vectorID })
            else { return nil }
            return "  - \(artifact.label) · L\(Int(slot.layer)) · alpha \(slot.alpha)"
        }
        if !activeSlots.isEmpty {
            lines.append("- Vector slots:")
            lines.append(contentsOf: activeSlots)
        }

        lines.append("")
        lines.append("## Transcript")
        lines.append("")
        // Conversation turns only: a live activity log is not a turn, and
        // exporting one under an "Assistant" heading would put a vector
        // build's progress lines into the record as model output.
        for message in conversationTranscript {
            lines.append("### \(Self.turnLabel(message))")
            lines.append("")
            lines.append(message.text.isEmpty ? "..." : message.text)
            lines.append("")
            if let original = message.originalText {
                lines.append("> **Original turn (not in active context)**")
                lines.append(">")
                lines.append(contentsOf: original.split(separator: "\n", omittingEmptySubsequences: false)
                    .map { "> \($0)" })
                lines.append("")
            }
        }
        return lines.joined(separator: "\n")
    }

    /// Adds a steering box, inheriting the previous box's settings and
    /// defaulting to the next unused vector (of the active workspace's
    /// catalog — server vectors in a server workspace).
    public func addSlot() {
        let previous = slots.last ?? SteerSlot()
        let used = Set(slots.compactMap(\.vectorID))
        if isServerWorkspace {
            let candidate =
                compatibleServerVectors.first { !used.contains($0.id) }
                ?? compatibleServerVectors.first
            var slot = SteerSlot(
                vectorID: candidate?.id, layer: previous.layer,
                alpha: previous.alpha, enabled: previous.enabled)
            if previous.vectorID == nil, let candidate {
                slot.layer = Double(candidate.layerCount / 2)
            }
            slots.append(slot)
            return
        }
        let candidate =
            compatibleVectors.first { !used.contains($0.id) } ?? compatibleVectors.first
        var slot = SteerSlot(
            vectorID: candidate?.id, layer: previous.layer,
            alpha: previous.alpha, enabled: previous.enabled)
        if previous.vectorID == nil, let candidate {
            slot.layer = Double(candidate.fixedSteeringLayer ?? candidate.sidecar.layerCount / 2)
        }
        slots.append(slot)
    }

    /// Removes a box; at least one always remains.
    public func removeSlot(_ id: UUID) {
        guard slots.count > 1 else {
            if let index = slots.firstIndex(where: { $0.id == id }) {
                slots[index].vectorID = nil
            }
            return
        }
        slots.removeAll { $0.id == id }
    }

    /// Selects a vector into the first slot (e.g. after saving a concept).
    public func selectVector(_ id: VectorArtifact.ID) {
        slots[0].vectorID = id
        applyDefaultsForSelectedVector(slotID: slots[0].id)
    }

