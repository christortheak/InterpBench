    /// Builds a neutral-PC basis from the selected neutral corpus.
    ///
    /// Defaults to the MIDDLE-THIRD layer band (2026-08-18). This used to
    /// capture every layer, which — combined with the row cap being applied
    /// only after collection — made an ordinary basis build a multi-GB ×
    /// layers transient that killed the app process. Ingestion is bounded now,
    /// but an all-layer bank is still ~3× the memory and ~3× the PCA of the
    /// band, and steering lives in the middle third anyway. `allLayers: true`
    /// is the explicit, expensive opt-out.
    public func buildNeutralPCBasis(
        minimumExplainedVariance: Double = 0.5,
        maximumComponentCount: Int =
            VectorExtractionRecipe.NeutralPCSelection.defaultMaximumComponentCount,
        allLayers: Bool = false
    ) async {
        guard !isBuildingNeutralPCBasis else { return }
        // The panel's model selector drives the capture: a bank measured on
        // the model that happened to be resident would be stamped with the
        // wrong modelID and silently mis-calibrate every alpha derived from it.
        if case .local = cluster.activeWorkspace {
            do {
                try await ensureSelectedLocalModelLoaded()
            } catch {
                neutralPCStatus = "neutral direction build failed: \(error)"
                return
            }
        }
        guard let container, let loadedModelID else {
            neutralPCStatus = "load a model before building neutral directions"
            return
        }
        isBuildingNeutralPCBasis = true
        neutralPCStatus = "building neutral directions from prompts/neutral/corpus.jsonl…"
        defer { isBuildingNeutralPCBasis = false }

        do {
            let corpusRecord = selectedNeutralCorpus
            let corpus = try NeutralCorpusStore.loadTexts(record: corpusRecord)
            let readingPosition = ReadingPosition.meanFromToken(50)
            let shape = try await ConceptExtractor.residualShape(container: container)
            let captureLayers =
                allLayers
                ? Set(0 ..< shape.blockCount)
                : LayerBand.middleThird(ofBlockCount: shape.blockCount)
            let bandDescription = LayerBand.description(
                of: captureLayers, blockCount: shape.blockCount)
            neutralPCStatus = "building neutral directions · \(bandDescription)…"
            let bank = try await ConceptExtractor.neutralActivationBank(
                container: container,
                texts: corpus.texts,
                readingPosition: readingPosition,
                layers: captureLayers,
                // Seed from the pinned corpus FILE hash: the same corpus
                // reproduces the same bounded token draw.
                downsampleSeed: TokenBankDownsampler.seed(fromCorpusHash: corpus.hash),
                log: { message in
                    FileHandle.standardError.write(Data((message + "\n").utf8))
                })
            let selection = VectorExtractionRecipe.NeutralPCSelection.explainedVariance(
                minimumExplainedVariance, maximumCount: maximumComponentCount)
            let components = try bank.componentsByLayer(selection: selection)
            let basis = NeutralPCBasis(
                modelID: loadedModelID,
                corpusKind: corpusRecord.kind,
                corpusName: corpusRecord.name,
                corpusHash: corpus.hash,
                corpusPath: NeutralCorpusStore.relativePath(for: corpusRecord.url),
                readingPosition: readingPosition,
                selectionDescription:
                    "neutral PCs \(Int((minimumExplainedVariance * 100).rounded()))% variance "
                    + "(≤\(selection.resolvedMaximumCount)/layer)",
                layers: bank.layers,
                componentsByLayer: components,
                residualNormPerLayer: bank.residualNormPerLayer,
                screening: bank.screening,
                tokenRowCount: bank.tokenRowCount,
                sourceRowsPerLayer: bank.sourceRowsPerLayer,
                usedRowsPerLayer: bank.usedRowsPerLayer,
                downsampleSeed: bank.downsampleSeed,
                rowCapPerLayer: TokenBankDownsampler.defaultRowCapPerLayer,
                minimumExplainedVariance: minimumExplainedVariance,
                maximumComponentCount: selection.resolvedMaximumCount,
                layerSelectionDescription: bandDescription)
            let record = try NeutralPCStore.save(basis)
            refreshNeutralPCBases()
            selectedNeutralPCBasisID = record.id
            neutralPCStatus =
                "saved \(corpusRecord.label) directions: \(basis.totalComponentCount) PCs across "
                + "\(basis.layers.count) layers (\(bandDescription)) from "
                + "\(bank.usedRowsPerLayer)/\(bank.sourceRowsPerLayer) token rows per layer"
        } catch {
            neutralPCStatus = "neutral direction build failed: \(error)"
        }
    }

    // MARK: - Selected-model enforcement for local builds

    /// What a LOCAL in-process build must do about the model before it runs
    /// forward passes. The builders' workspace-scoped model selectors DRIVE
    /// the model (substrate-as-workspace); they do not advise about whatever
    /// the Playground happens to have resident.
    public enum LocalModelLoadDecision: Equatable, Sendable {
        /// The selected model is already the loaded one — run.
        case proceed
        /// Load this model through the Playground's own load path first.
        case load(String)
        /// Something else is already using the in-process model; say so
        /// instead of racing it (`loadModel` tears down the session).
        case refuse(reason: String)
    }

    /// The decision, engine-pure so it is testable without a real model.
    /// `isLoading` is "a local load is already in flight", `isGenerating` is
    /// "a chat generation is streaming" — either makes a model swap a race,
    /// and `loadModel()` resets the container, session, and transcript.
    public nonisolated static func localModelLoadDecision(
        selectedModelID: String,
        loadedModelID: String?,
        isLoading: Bool,
        isGenerating: Bool
    ) -> LocalModelLoadDecision {
        if let loadedModelID, loadedModelID == selectedModelID { return .proceed }
        if isGenerating {
            return .refuse(
                reason: "a chat generation is running — wait for it to finish, then "
                    + "build (building loads \(selectedModelID) and resets the chat)")
        }
        if isLoading {
            return .refuse(
                reason: "a model load is already in progress — wait for it to "
                    + "finish, then build")
        }
        return .load(selectedModelID)
    }

    /// Why a LOCAL in-process build action must stay disabled right now, or
    /// `nil` when it may start. Engine-pure so the rule is testable without a
    /// model.
    ///
    /// This is the enablement half of `localModelLoadDecision`, and it is
    /// deliberately NOT "a model is loaded and ready". A build whose first
    /// step is `ensureSelectedLocalModelLoaded()` loads the SELECTED model
    /// itself, so a cold start — nothing loaded at all — is enabled: gating on
    /// residency forced a detour through the Playground before every first
    /// build of a session. What genuinely conflicts is another user of the
    /// in-process model: a build already running, a streaming chat generation,
    /// or a load already in flight (`loadModel()` tears down the container,
    /// session, and transcript, so racing one is not a matter of taste). Those
    /// are exactly the states `localModelLoadDecision` refuses, which keeps the
    /// button and the build it starts from disagreeing.
    ///
    /// Not for actions that read `containerForExtraction` / `loadedModelID`
    /// directly without that ensure step — those still need a loaded model.
    public nonisolated static func localBuildBlockedReason(
        isBuilding: Bool,
        isLoading: Bool,
        isGenerating: Bool
    ) -> String? {
        if isBuilding { return "a build is already running" }
        if isGenerating {
            return "a chat generation is running — building would load the "
                + "selected model and reset the chat"
        }
        if isLoading { return "a model load is already in progress" }
        return nil
    }

    /// Instance form: the same rule read off this service's live state.
    public func localBuildBlockedReason(isBuilding: Bool) -> String? {
        let isLoading: Bool
        if case .loading = state { isLoading = true } else { isLoading = false }
        return Self.localBuildBlockedReason(
            isBuilding: isBuilding, isLoading: isLoading, isGenerating: isGenerating)
    }

    /// The panel's model-selection caption for a LOCAL workspace: what the
    /// next build will do about the model, or `nil` when the selection is
    /// already resident and there is nothing to say. Honest about the cold
    /// start — "no model loaded" is a state building handles, not a blocker.
    public nonisolated static func localModelSelectionCaption(
        selectedModelID: String,
        loadedModelID: String?,
        isInstalled: Bool = true
    ) -> String? {
        // "Building will load it" is a promise the build cannot keep for
        // weights that are not on the Mac — it would refuse. Say the real
        // next step instead.
        guard isInstalled else {
            return "\(selectedModelID) is not downloaded — use Add Model… to "
                + "fetch it before building"
        }
        guard let loadedModelID else {
            return "no model loaded — building will load \(selectedModelID)"
        }
        guard loadedModelID != selectedModelID else { return nil }
        return "\(loadedModelID) is currently loaded — building will load "
            + "\(selectedModelID) and reset the chat"
    }

    /// Local counterpart to the server builds' `ensureSelectedServerModelLoaded`:
    /// make the SELECTED local model the loaded one before an in-process build
    /// runs forward passes. Reuses `loadModel()` — the exact path the
    /// Playground's Load button drives, including its progress reporting,
    /// memory handling, and session teardown — and throws on failure so a
    /// build can never silently extract on whatever model happened to be
    /// resident. Callers must re-read `containerForExtraction` / `loadedModelID`
    /// AFTER awaiting this: a load replaces the container.
    public func ensureSelectedLocalModelLoaded() async throws {
        let isLoading: Bool
        if case .loading = state { isLoading = true } else { isLoading = false }
        switch Self.localModelLoadDecision(
            selectedModelID: selectedModelID,
            loadedModelID: loadedModelID,
            isLoading: isLoading,
            isGenerating: isGenerating)
        {
        case .proceed:
            return
        case .refuse(let reason):
            throw ChatServiceError(reason: reason)
        case .load(let modelID):
            await loadModel()
            guard loadedModelID == modelID, state == .ready else {
                throw ChatServiceError(
                    reason: errorMessage ?? "could not load \(modelID)")
            }
            // Logged after the load: `loadModel()` clears the transcript the
            // live log lives in.
            _ = startLiveLog(
                title: "Model — \(modelID)",
                initialLine: "Loaded \(modelID) for this build; the builder's "
                    + "model selection drives local extraction.")
        }
    }

    /// What the Local workspace's model button should DO for a selection:
    /// load it, or offer the download it needs first. Engine-pure so the gate
    /// is testable without a cache or a network.
    ///
    /// This is the rule that makes a fresh machine survivable. Before it, the
    /// Playground listed six pinned tiers as if they were all present and
    /// `loadModel()` handed an absent one straight to the Hugging Face
    /// downloader, which fetched several gigabytes with no visible progress
    /// in the section, no cancel, and no bound on how long it could sit there.
    public enum LocalModelAction: Equatable, Sendable {
        /// Weights are in the local cache — load it.
        case load(String)
        /// Not installed: offer the download explicitly, by name.
        case download(String)
        /// Nothing can start right now (a load or install is in flight).
        case busy(reason: String)
    }

    public nonisolated static func localModelAction(
        selectedModelID: String,
        isInstalled: Bool,
        isLoading: Bool,
        isInstalling: Bool
    ) -> LocalModelAction {
        if isLoading {
            return .busy(reason: "a model load is already in progress")
        }
        if isInstalling {
            return .busy(reason: "a model download is already in progress")
        }
        return isInstalled ? .load(selectedModelID) : .download(selectedModelID)
    }

    /// Why a local load must refuse this model, or nil when it may proceed.
    /// The one refusal `loadModel()` enforces itself, so no caller — the
    /// Playground button, a builder's `ensureSelectedLocalModelLoaded`, the
    /// headless web host — can start an invisible multi-gigabyte download.
    public nonisolated static func localLoadRefusal(
        modelID: String, isInstalled: Bool
    ) -> String? {
        guard !isInstalled else { return nil }
        return "\(modelID) is not installed on this Mac — use Download to "
            + "fetch its weights (several GB) first; Load never downloads"
    }

    public func loadModel() async {
        guard state != .loading(percent: 0) else { return }
        // Fail closed on a missing model, with the cache re-scanned first so
        // the refusal and the picker's availability badges agree.
        catalog.refreshLocalInstalledModels()
        if let refusal = Self.localLoadRefusal(
            modelID: selectedModelID,
            isInstalled: catalog.isInstalled(selectedModelID, in: .local))
        {
            errorMessage = refusal
            return
        }
        state = .loading(percent: 0)
        errorMessage = nil
        transcript = []
        liveLogMessageIDs.removeAll()
        chatContextTokenEstimate = 0
        chatContextEstimateNeedsRefresh = false
        session = nil
        container = nil
        loadedModelID = nil
        vectorCache.removeAll()
        neutralMeanCache.removeAll()
        slots = [SteerSlot()]  // vectors are model-specific; slots can't survive a switch
        selectedRuntimeAdapterID = nil

        MLX.Memory.cacheLimit = 2 * 1024 * 1024 * 1024

        do {
            let spec = selectedModel
            let loaded = try await SteeredContainerLoader.load(modelID: spec.id) { [weak self] progress in
                let percent = Int(progress.fractionCompleted * 100)
                Task { @MainActor [weak self] in
                    if case .loading = self?.state { self?.state = .loading(percent: percent) }
                }
            }
            container = loaded
            loadedModelID = spec.id
            startSession()
            state = .ready
            refreshVectors()  // defaults slot 0 to the first compatible vector
            applySelectedModelVariantIfReady()
            concepts.refreshStaleness()  // pass counts depend on the loaded model
        } catch {
            errorMessage = "load failed: \(error)"
            state = .unloaded
        }
    }

    public func resetChat() {
        transcript = []
        liveLogMessageIDs.removeAll()
        chatContextTokenEstimate = 0
        chatContextEstimateNeedsRefresh = false
        startSession()
    }

    public func send(_ text: String) {
        let prompt = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let canSend =
            cluster.computeTarget == .local
            ? state == .ready
            : cluster.client != nil
                && (serverHasLoadedModel
                    || selectedRemoteVariantPath != nil
                    // Inline variant spec composed from the live controls: the
                    // server acquires the spec's base model itself.
                    || (selectedRemoteModelID != nil
                        && serverControlState().hasInterventions))
        guard !prompt.isEmpty, canSend, !isGenerating else { return }
        // Chat-template pre-flight: refuse a send whose user turn the active
        // model's template could not render (e.g. consecutive user turns
        // after a seeded user turn on gemma-3) — inline explanation instead
        // of a server 400 / local render throw.
        if let reason = turnConstraintReason(for: .user) {
            errorMessage = reason
            return
        }

        clearLiveLogs()
        transcript.append(ChatMessage(role: .user, text: prompt))
        transcript.append(ChatMessage(role: .assistant, text: ""))
        isGenerating = true
        errorMessage = nil
        probeStatus = nil

        generationTask = Task {
            switch self.cluster.computeTarget {
            case .local:
                await self.runGeneration(prompt: prompt)
            case .server:
                await self.runRemoteGeneration(prompt: prompt)
            }
        }
    }

    /// Cancels the in-flight response. The partial text stays in the
    /// transcript (and in the session's history).
    public func stopGeneration() {
        generationTask?.cancel()
    }

    // MARK: - Send-as-assistant (seeded turns) & prefix continuation

    /// The model whose chat template will render the transcript — the local
    /// loaded model, or the server-side model the next send resolves to (a
    /// stored variant's base model, else the selected/default server model).
    /// Nil when unknown; pre-flight then imposes no constraints and the
    /// server's structured 400 is the backstop.
    private var activeChatModelID: String? {
        switch cluster.computeTarget {
        case .local:
            return loadedModelID ?? selectedModelID
        case .server:
            if let path = selectedRemoteVariantPath, !path.isEmpty,
                let variant = cluster.remoteVariants.first(where: { $0.path == path })
            {
                return variant.baseModelID
            }
            return selectedRemoteModelID ?? serverDefaultLoadedModelID
        }
    }

    /// Roles of the transcript turns that will actually render — live-log
    /// messages and whitespace-only turns are excluded, matching the family
    /// adapter's (`chatHistoryMessages` / server `render_messages`) cleaning.
    private var renderedTranscriptRoles: [ExperimentTasks.ChatTurn.Role] {
        transcript.compactMap { message in
            guard !liveLogMessageIDs.contains(message.id),
                !message.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            else { return nil }
            return message.role == .user ? .user : .assistant
        }
    }

    /// Pre-flight against the active model's chat-template conversation
    /// constraints: the reason APPENDING a turn of this role could not be
    /// rendered (e.g. gemma-3 requires user-first strict alternation), or
    /// nil. Raw-completion mode renders no chat template, so it is never
    /// constrained. The composer disables Seed/Send/Continue with this
    /// reason instead of letting the request 400.
    public func turnConstraintReason(for role: ComposerRole) -> String? {
        guard promptMode == .chatAssistant, let modelID = activeChatModelID else {
            return nil
        }
        return ExperimentTasks.conversationConstraintViolation(
            appending: role == .user ? .user : .assistant,
            toTranscriptRoles: renderedTranscriptRoles,
            modelID: modelID)
    }

    /// Why seeding an assistant turn is unavailable right now — nil when it
    /// is available. The composer shows this as the standing reason; the
    /// seed action refuses with the same string (one rule, no drift).
    public var seedUnavailableReason: String? {
        if isGenerating { return "wait for the current generation to finish" }
        guard promptMode == .chatAssistant else {
            return "send-as-assistant requires chat mode — raw completion has "
                + "no assistant turns to seed"
        }
        switch cluster.computeTarget {
        case .local:
            // A model must be loaded: loading clears the transcript, so a
            // turn seeded earlier would silently vanish.
            guard state == .ready else { return "load a model before seeding a turn" }
        case .server:
            guard cluster.client != nil else { return "invalid server URL" }
            guard let capabilities = cluster.capabilities else {
                return "connect to the server first (capabilities unknown)"
            }
            guard capabilities.supportsSeededChatTurns else {
                return "this server does not support seeded assistant turns "
                    + "(no chat.seededTurns capability) — upgrade the server "
                    + "to send as Assistant"
            }
        }
        return turnConstraintReason(for: .assistant)
    }

    /// Why seeding a USER turn is unavailable (nil = available). A seeded
    /// user turn appends WITHOUT generating — the scripted-transcript tool,
    /// and the canonical fix for user-first templates (lead with a user
    /// turn, then seed the assistant reply). No server capability is needed:
    /// user turns carry no provenance flag (they are always
    /// researcher-authored) and ride the ordinary messages transcript.
    public var seedUserUnavailableReason: String? {
        if isGenerating { return "wait for the current generation to finish" }
        guard promptMode == .chatAssistant else {
            return "seeding requires chat mode — raw completion has no turn "
                + "structure to seed into"
        }
        switch cluster.computeTarget {
        case .local:
            // Same rule as assistant seeding: loading clears the transcript.
            guard state == .ready else { return "load a model before seeding a turn" }
        case .server:
            guard cluster.client != nil else { return "invalid server URL" }
        }
        return turnConstraintReason(for: .user)
    }

    /// Assistant-prefix continuation availability (nil = available). Local
    /// MLX renders the continuation itself; a server must advertise
    /// `chat.continueFinalMessage`.
    public var continuationUnavailableReason: String? {
        if let reason = seedUnavailableReason { return reason }
        if cluster.computeTarget == .server,
            cluster.capabilities?.supportsAssistantPrefillContinuation != true
        {
            return "this server does not support assistant-prefix "
                + "continuation (no chat.continueFinalMessage capability)"
        }
        return nil
    }

    /// Appends `text` to the transcript AS AN ASSISTANT TURN without
    /// generating — the model will treat it as its own prior turn on the
    /// next generation (rendered through the model family's real assistant
    /// format via the chat template; never string-pasted). The turn is
    /// marked `seeded` everywhere it is recorded.
    public func seedAssistantTurn(_ text: String) {
        let content = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !content.isEmpty else { return }
        if let reason = seedUnavailableReason {
            errorMessage = reason
            return
        }
        clearLiveLogs()
        errorMessage = nil
        transcript.append(ChatMessage(role: .assistant, text: content, seeded: true))
        // The live ChatSession's KV history does not contain this turn; the
        // next local generation replays the transcript through the template.
        pendingSeededHistoryReplay = true
        if let container {
            let seededText = content
            Task { [weak self] in
                let tokens = await self?.tokenCount(seededText, in: container) ?? 0
                await MainActor.run { self?.chatContextTokenEstimate += tokens }
            }
        }
    }

    /// Appends `text` to the transcript AS A USER TURN without generating —
    /// the scripted-transcript counterpart of `seedAssistantTurn`, and the
    /// canonical way to satisfy user-first templates (gemma-3) before
    /// seeding an assistant reply. User turns carry no provenance flag:
    /// they are always researcher-authored.
    public func seedUserTurn(_ text: String) {
        let content = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !content.isEmpty else { return }
        if let reason = seedUserUnavailableReason {
            errorMessage = reason
            return
        }
        clearLiveLogs()
        errorMessage = nil
        transcript.append(ChatMessage(role: .user, text: content))
        // The live ChatSession's KV history does not contain this turn; the
        // next local generation replays the transcript through the template.
        pendingSeededHistoryReplay = true
        if let container {
            let seededText = content
            Task { [weak self] in
                let tokens = await self?.tokenCount(seededText, in: container) ?? 0
                await MainActor.run { self?.chatContextTokenEstimate += tokens }
            }
        }
    }

    // MARK: - Transcript editing (edit any turn / remove the last turn)

    /// Replaces a transcript message's text in place, with the provenance
    /// rules the record depends on (hard requirement):
    /// - editing a GENERATED assistant turn sets `edited` (generated-then-
    ///   altered — distinct from `seeded`);
    /// - editing a wholly SEEDED turn keeps `seeded` only (still authored
    ///   wholesale);
    /// - editing a CONTINUED turn keeps `seeded`, sets `edited`, and drops
    ///   the prefix length (it no longer describes the text);
    /// - editing a USER turn sets nothing (always researcher-authored).
    /// Any edit invalidates the local session history exactly like seeding
    /// (`pendingSeededHistoryReplay`), so the next generation rebuilds the
    /// history through the chat template.
    public func editTranscriptMessage(id: UUID, newText: String) {
        guard !isGenerating else {
            errorMessage = "wait for the current generation to finish"
            return
        }
        guard let index = transcript.firstIndex(where: { $0.id == id }),
            !liveLogMessageIDs.contains(id)
        else { return }
        _ = applyTranscriptEdit(at: index, newText: newText)
    }

    /// Saves an assistant edit and makes that turn the end of the active
    /// branch. The composer returns to User so the researcher can supply the
    /// next turn. Later turns are removed from model context; the edited
    /// turn's first version remains available through `originalText`.
    public func returnControlToUserFromAssistant(id: UUID, newText: String) {
        guard !isGenerating else {
            errorMessage = "wait for the current generation to finish"
            return
        }
        guard let index = transcript.firstIndex(where: { $0.id == id }),
            transcript[index].role == .assistant,
            !liveLogMessageIDs.contains(id),
            applyTranscriptEdit(at: index, newText: newText)
        else { return }
        truncateTranscript(after: index)
        composerRole = .user
        errorMessage = nil
    }

    /// Saves an assistant edit, discards the later active branch, and asks the
    /// model to continue from the edited assistant text itself. Selecting this
    /// action adopts that text as a researcher-controlled assistant prefix,
    /// which is stamped with the existing seeded-prefix provenance.
    public func continueGenerationFromAssistant(id: UUID, newText: String) {
        guard !isGenerating else {
            errorMessage = "wait for the current generation to finish"
            return
        }
        if let reason = continuationEngineUnavailableReason {
            errorMessage = reason
            return
        }
        guard let index = transcript.firstIndex(where: { $0.id == id }),
            transcript[index].role == .assistant,
            !liveLogMessageIDs.contains(id),
            applyTranscriptEdit(at: index, newText: newText)
        else { return }
        truncateTranscript(after: index)
        Self.stampContinuationProvenance(on: &transcript[index])
        startContinuationGeneration()
    }

    /// Records where this continuation starts without rewriting an existing
    /// researcher-authored boundary. In particular, continuing a mixed turn a
    /// second time moves only `continuationPrefixLength`; its generated tail
    /// must never become part of `seededPrefixLength`.
    nonisolated static func stampContinuationProvenance(on message: inout ChatMessage) {
        let prefixLength = message.text.count
        message.continuationPrefixLength = prefixLength
        if message.seeded, !message.edited, message.seededPrefixLength == nil {
            message.seededPrefixLength = prefixLength
        }
    }

    /// Saves a user edit, discards every later turn, and regenerates the
    /// assistant reply from that user turn. This is a branch operation, not a
    /// second appended user message.
    public func restartConversationFromUser(id: UUID, newText: String) {
        guard !isGenerating else {
            errorMessage = "wait for the current generation to finish"
            return
        }
        if let reason = generationTargetUnavailableReason {
            errorMessage = reason
            return
        }
        guard let index = transcript.firstIndex(where: { $0.id == id }),
            transcript[index].role == .user,
            !liveLogMessageIDs.contains(id),
            applyTranscriptEdit(at: index, newText: newText)
        else { return }
        let prompt = transcript[index].text
        truncateTranscript(after: index)
        transcript.append(ChatMessage(role: .assistant, text: ""))
        isGenerating = true
        errorMessage = nil
        probeStatus = nil
        generationTask = Task {
            switch self.cluster.computeTarget {
            case .local:
                await self.runGeneration(prompt: prompt)
            case .server:
                await self.runRemoteGeneration(prompt: prompt)
            }
        }
    }

    /// Availability used by the turn editor. Unlike
    /// `continuationUnavailableReason`, this does not ask whether a NEW
    /// assistant turn can be appended: the edited assistant turn already
    /// exists and becomes the final message before continuation.
    public var continuationFromEditUnavailableReason: String? {
        continuationEngineUnavailableReason
    }

    /// Availability used by the user-turn editor's Restart action.
    public var restartFromEditUnavailableReason: String? {
        generationTargetUnavailableReason
    }

    @discardableResult
    private func applyTranscriptEdit(at index: Int, newText: String) -> Bool {
        let text = newText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else {
            errorMessage = "an edited turn cannot be empty — use Remove turn "
                + "to delete the last message instead"
            return false
        }
        guard text != transcript[index].text else {
            errorMessage = nil
            return true
        }
        if transcript[index].originalText == nil {
            transcript[index].originalText = transcript[index].text
        }
        transcript[index].text = text
        // Probe spans were scored against the old text; they no longer apply.
        transcript[index].probeSpans = []
        if transcript[index].role == .assistant {
            if transcript[index].seededPrefixLength != nil
                || transcript[index].continuationPrefixLength != nil
            {
                // The old continuation boundary no longer describes the
                // rewritten text, regardless of who authored its prefix.
                transcript[index].seededPrefixLength = nil
                transcript[index].continuationPrefixLength = nil
                transcript[index].edited = true
            } else if !transcript[index].seeded {
                transcript[index].edited = true
            }
        }
        pendingSeededHistoryReplay = true
        chatContextEstimateNeedsRefresh = true
        errorMessage = nil
        return true
    }

    private func truncateTranscript(after index: Int) {
        guard index < transcript.count else { return }
        if index + 1 < transcript.count {
            let removedIDs = Set(transcript[(index + 1)...].map(\.id))
            liveLogMessageIDs.subtract(removedIDs)
            transcript.removeSubrange((index + 1)..<transcript.endIndex)
        }
        pendingSeededHistoryReplay = true
        chatContextTokenEstimate = 0
        chatContextEstimateNeedsRefresh = true
    }

    private var generationTargetUnavailableReason: String? {
        switch cluster.computeTarget {
        case .local:
            return state == .ready ? nil : "load a model before restarting from this turn"
        case .server:
            guard cluster.client != nil else { return "invalid server URL" }
            guard serverHasLoadedModel || selectedRemoteVariantPath != nil
                || (selectedRemoteModelID != nil && serverControlState().hasInterventions)
            else { return "load a server model or select a server agent first" }
            return nil
        }
    }

    private var continuationEngineUnavailableReason: String? {
        if isGenerating { return "wait for the current generation to finish" }
        guard promptMode == .chatAssistant else {
            return "assistant continuation requires chat mode"
        }
        if let reason = generationTargetUnavailableReason { return reason }
        if cluster.computeTarget == .server {
            guard let capabilities = cluster.capabilities else {
                return "connect to the server first (capabilities unknown)"
            }
            guard capabilities.supportsSeededChatTurns else {
                return "this server does not support seeded assistant turns "
                    + "(no chat.seededTurns capability)"
            }
            guard capabilities.supportsAssistantPrefillContinuation else {
                return "this server does not support assistant-prefix "
                    + "continuation (no chat.continueFinalMessage capability)"
            }
        }
        return nil
    }

    private func refreshLocalContextEstimateIfNeeded(prefixCount: Int) async {
        guard chatContextEstimateNeedsRefresh, cluster.computeTarget == .local,
            let container
        else { return }
        var total = 0
        for message in transcript.prefix(max(0, prefixCount))
        where !liveLogMessageIDs.contains(message.id) {
            total += await tokenCount(message.text, in: container)
        }
        chatContextTokenEstimate = total
        chatContextEstimateNeedsRefresh = false
    }

    /// Whether this message is an editable transcript turn (live activity
    /// logs render in the transcript but are not conversation turns).
    public func canEditTranscriptMessage(_ message: ChatMessage) -> Bool {
        !liveLogMessageIDs.contains(message.id)
    }

    /// Whether this message can be removed — only the LAST transcript turn
    /// (mid-transcript surgery is deliberately not offered), and never while
    /// generating.
    public func canRemoveTranscriptMessage(_ message: ChatMessage) -> Bool {
        !isGenerating && transcript.last?.id == message.id
            && !liveLogMessageIDs.contains(message.id)
    }

    /// Removes the trailing transcript turn (assistant or user) — the simple
    /// fix for a mis-seed. Refuses anything but the last turn.
    public func removeLastTranscriptMessage() {
        guard !isGenerating else {
            errorMessage = "wait for the current generation to finish"
            return
        }
        guard let last = transcript.last, !liveLogMessageIDs.contains(last.id)
        else { return }
        transcript.removeLast()
        pendingSeededHistoryReplay = true
        chatContextEstimateNeedsRefresh = true
        errorMessage = nil
    }

    /// Seeds an INCOMPLETE assistant turn and has the model continue it —
    /// generation starts mid-assistant-turn with no new generation prompt
    /// ("prefill"). The transcript records the researcher-authored prefix
    /// length so the mixed turn is never mistaken for a pure generation.
    public func continueSeededAssistantTurn(_ text: String) {
        // Deliberately NOT trimmed at the end: a trailing space is a
        // meaningful prefill choice — though note both engines' template
        // cleaning trims it (transformers' continue_final_message rstrip).
        let prefix = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !prefix.isEmpty else { return }
        if let reason = continuationUnavailableReason {
            errorMessage = reason
            return
        }
        clearLiveLogs()
        var message = ChatMessage(role: .assistant, text: prefix, seeded: true)
        message.seededPrefixLength = prefix.count
        message.continuationPrefixLength = prefix.count
        transcript.append(message)
        pendingSeededHistoryReplay = true
        startContinuationGeneration()
    }

    private func startContinuationGeneration() {
        isGenerating = true
        errorMessage = nil
        probeStatus = nil

        generationTask = Task {
            switch self.cluster.computeTarget {
            case .local:
                await self.runLocalContinuation()
            case .server:
                await self.runRemoteGeneration(prompt: "", continuation: true)
            }
        }
    }

    /// The transcript as wire messages — the one mapping between the UI
    /// transcript and the roles-tagged message-object contract
    /// (`{"role","content","seeded"?,"edited"?}`), used by every remote
    /// generation path. Both flags are nullable, absent = false; servers
    /// treat them as record-only provenance and ignore them for rendering.
    /// Pure and static so the roles+provenance mapping is unit-tested
    /// without a server.
    nonisolated static func wireMessages(from turns: [ChatMessage]) -> [ChatWireMessage] {
        turns.map { message in
            ChatWireMessage(
                role: message.role == .user ? "user" : "assistant",
                content: message.text,
                seeded: message.isSeededOrContinued ? true : nil,
                edited: message.edited ? true : nil)
        }
    }

    /// Local assistant-prefix continuation: render the transcript (whose
    /// final turn is the seeded prefix) WITHOUT a generation prompt via the
    /// template stack, then generate from those exact tokens. Streamed text
    /// appends to the seeded message.
    private func runLocalContinuation() async {
        defer {
            isGenerating = false
            generationTask = nil
        }
        lastServerVariantProvenance = nil
        guard let container, let loadedModelID else { return }
        do {
            await refreshLocalContextEstimateIfNeeded(prefixCount: transcript.count - 1)
            // The MLXLMCommon tokenizer bridge only exposes the
            // generation-prompt render; load the raw swift-transformers
            // tokenizer from the model's cached snapshot for the
            // continuation render.
            guard
                let snapshot = SteeredContainerLoader.cachedSnapshotDirectory(
                    for: loadedModelID)
            else {
                throw ChatServiceError(
                    reason: "no cached tokenizer snapshot for \(loadedModelID)")
            }
            let tokenizer = try await AutoTokenizer.from(modelFolder: snapshot)
            let turns = transcript.map {
                ExperimentTasks.ChatTurn(
                    role: $0.role == .user ? .user : .assistant,
                    text: $0.text,
                    seeded: $0.isSeededOrContinued)
            }
            let rendered = try ExperimentTasks.continuationRender(
                tokenizer: tokenizer,
                turns: turns,
                modelID: loadedModelID,
                systemPrompt: nilIfEmpty(systemPrompt),
                qwenThinkingEnabled: qwenThinkingEnabled)

            var activeAdapter: LoRAContainer?
            defer {
                if let activeAdapter {
                    Task { await self.unloadAdapter(activeAdapter, from: container) }
                }
            }
            activeAdapter = try await applyCurrentAdapter(to: container)
            let output = try await ExperimentTasks.generate(
                container,
                promptTokenIDs: rendered.tokenIDs,
                modelID: loadedModelID,
                maxTokens: maxTokens,
                temperature: temperature,
                injections: try currentInjections()
            ) { [weak self] output in
                await MainActor.run {
                    guard let self, let last = self.transcript.indices.last,
                        let prefixLength = self.transcript[last].continuationPrefixLength
                    else { return }
                    let prefix = String(self.transcript[last].text.prefix(prefixLength))
                    self.transcript[last].text = prefix + output
                }
            }
            if let last = transcript.indices.last,
                let prefixLength = transcript[last].continuationPrefixLength
            {
                let prefix = String(transcript[last].text.prefix(prefixLength))
                transcript[last].text = prefix + output
            }
            let continued = transcript.last?.text ?? ""
            chatContextTokenEstimate += await tokenCount(continued, in: container)
            // The session's KV history still lacks this turn; replay stays
            // pending for the next ordinary send.
            pendingSeededHistoryReplay = true
        } catch is CancellationError {
            // user pressed Stop — the partial continuation stays, honestly
            // marked with its seeded prefix length
        } catch {
            if Self.isCancellation(error) { return }
            errorMessage = "continuation failed: \(error)"
        }
    }

    /// Connect via the shared store, then default the chat's remote model
    /// selection to whatever the server already has loaded, and refresh the
    /// catalog's view of the server's derived artifacts.
    /// Startup patience for `connectCluster`: how many total attempts and the
    /// pause between them when the ONE retryable failure occurs (tunnel up,
    /// controller not answering — the daemon's torch-import window). 8 × 15 s
    /// covers the ~2 minutes observed live; tests set the delay to zero.
    public var connectStartupRetryLimit = 8

    /// Result of the last judge-key sync (key custody, 2026-07-19): nil =
    /// never attempted this launch; empty string = synced clean; anything
    /// else = the human-readable error. The Compute section's External
    /// judge key row renders this.
    public private(set) var judgeKeySyncResult: String?

    /// Push (or, when cleared, REMOVE) the external judge key on the
    /// cluster right now — the settings row's explicit action. Connect does
    /// the same sync automatically; this exists so "Save" takes effect
    /// without a reconnect when a tunnel is already up.
    public func syncJudgeKeyNow() async {
        guard let site = cluster.activeSite, site.isSSHTransport,
            let tunnel = cluster.attachedTunnel
        else {
            judgeKeySyncResult = "no SSH cluster site active — the key "
                + "syncs automatically at the next cluster connect"
            return
        }
        judgeKeySyncResult = await tunnel.syncJudgeKey(JudgeKeyStore.stored())
            ?? ""
    }
    public var connectStartupRetryDelay: Duration = .seconds(15)

    public func connectCluster() async {
        // Every app surface funnels through this method. SSH-backed sites need
        // their forward established before ClusterConnectionStore can make an
        // HTTP request; previously only the connection-dot path did that work,
        // while the toolbar substrate picker called this method directly and
        // attempted the stale localhost URL in the saved entry.
        if let site = cluster.activeSite, site.isSSHTransport {
            guard let tunnel = cluster.attachedTunnel else {
                cluster.status = "connection failed: SSH tunnel manager is unavailable"
                return
            }
            tunnel.configure(site: site)
            cluster.status = "opening SSH tunnel..."
            await tunnel.open()
            guard case .up(let port) = tunnel.state else {
                cluster.status = Self.tunnelConnectionFailure(site: site, state: tunnel.state)
                return
            }
            cluster.noteTunnelLocalPort(port)
            // Judge-key custody sync (2026-07-19): EVERY connect pushes the
            // stored external judge key to ~/.steerlab/judge-key (mode 600,
            // stdin transport) — or REMOVES the remote file when the key
            // was cleared here, so deletion propagates and rotation is
            // "save + reconnect". Best-effort: a sync failure never blocks
            // the connection; the result surfaces in the Compute section.
            judgeKeySyncResult = await tunnel.syncJudgeKey(
                JudgeKeyStore.stored()) ?? ""
        }

        var connected = await cluster.connect()
        // A freshly (re)submitted controller writes serverd.host BEFORE it
        // execs the server, and the Python side then spends a minute-plus
        // importing torch off the shared filesystem before uvicorn binds —
        // so "tunnel up, nobody answering" is the NORMAL startup window, not
        // a failure (observed live: Connect succeeded manually a couple of
        // minutes later, twice). Retry that specific case with patience;
        // every other failure returns immediately as before.
        var attempt = 1
        while !connected, attempt < connectStartupRetryLimit, !Task.isCancelled,
            cluster.status?.contains("controller is not answering") == true
        {
            attempt += 1
            cluster.status =
                "controller not answering yet — a freshly submitted controller "
                + "job takes a couple of minutes to start; retrying "
                + "(\(attempt)/\(connectStartupRetryLimit))..."
            try? await Task.sleep(for: connectStartupRetryDelay)
            guard !Task.isCancelled else { return }
            connected = await cluster.connect()
        }
        guard connected else { return }
        // Strict availability: a server workspace offers only that server's
        // installed models. A selection carried over from another
        // workspace/server (or from a cache that changed) must not survive as
        // if it were installed here.
        if let selected = selectedRemoteModelID, !remoteModelOptions.contains(selected) {
            selectedRemoteModelID = nil
        }
        if selectedRemoteModelID == nil {
            selectedRemoteModelID =
                serverDefaultLoadedModelID ?? remoteModelOptions.first
        }
        await refreshServerSteeringArtifacts()
    }

    nonisolated private static func tunnelConnectionFailure(
        site: ClusterSiteProfile, state: TunnelState
    ) -> String {
        let endpoint: String
        if case .ssh(let host, _, _, _) = site.transport {
            endpoint = host.trimmingCharacters(in: .whitespacesAndNewlines)
        } else {
            endpoint = site.name
        }
        switch state {
        case .needsAuth:
            return "connection failed: no SSH ControlMaster for \(endpoint) — "
                + "the site endpoint must exactly match the authenticated user@host; "
                + "choose Authenticate in the connection menu"
        case .degraded(let reason):
            return "connection failed: \(reason)"
        case .opening:
            return "connection failed: SSH tunnel to \(endpoint) is still opening"
        case .idle, .closed:
            return "connection failed: SSH tunnel to \(endpoint) is not open"
        case .up:
            return "connection failed: SSH tunnel state changed unexpectedly"
        }
    }

    /// True while a remote model load is in flight. The Load control
    /// disables on it (engineer review 2026-07-17: repeated clicks launched
    /// overlapping streams, and switching models made whichever request
    /// finished last win).
    public private(set) var isRemoteModelLoading = false
    private var remoteLoadTask: Task<Void, Never>?

    /// Cancel the in-flight remote load. Client-side only: the server may
    /// finish the load and keep the model resident — which is fine, the next
    /// load of that model returns instantly.
    public func cancelRemoteLoad() {
        remoteLoadTask?.cancel()
    }

    public func loadRemoteModel() async {
        guard !isRemoteModelLoading else { return }
        isRemoteModelLoading = true
        defer {
            isRemoteModelLoading = false
            remoteLoadTask = nil
        }
        let task = Task { await self.performRemoteLoad() }
        remoteLoadTask = task
        await task.value
    }

    private func performRemoteLoad() async {
        guard let client = cluster.client else {
            cluster.activity = "invalid server URL"
            return
        }
        guard let model = selectedRemoteModelID, !model.isEmpty else {
            cluster.activity = "select a server model first"
            return
        }
        do {
            cluster.activity = "loading \(model)..."
            if cluster.capabilities?.supportsStreamingLoad == true {
                // Streaming load: server heartbeats ("…(45s elapsed)") tick
                // the caption through a slow cold load, and no client
                // timeout ceiling can abort a load that is succeeding.
                try await client.streamLoadModel(model) { [weak self] status in
                    await MainActor.run { self?.cluster.activity = status }
                }
            } else {
                try await client.loadModel(model)
            }
            cluster.remoteState = try await client.state()
            cluster.activity = "loaded \(model)"
        } catch let error as ClusterClient.ClientError {
            // The controller's 409 "no GPU session" refusal is a next-step,
            // not a failure: point at the control that starts one.
            if case .badResponse(let code, let body) = error,
                let hint = GPUSessionRefusal.hint(code: code, body: body)
            {
                cluster.activity = hint
            } else {
                cluster.activity = "remote load failed: "
                    + ClusterClient.unwrappingDetail(error).description
            }
        } catch {
            if Self.isCancellation(error) {
                cluster.activity = "load canceled — the server may still "
                    + "finish and keep the model resident"
                return
            }
            cluster.activity = "remote load failed: \(error)"
        }
    }

    public func uploadSelectedVariantToServer() async {
        guard let client = cluster.client else {
            cluster.activity = "invalid server URL"
            return
        }
        // The definition to store server-side: the local definition selected
        // in THIS workspace's Playground picker when there is one, else the
        // Local workspace's steering-variant selection (historical path).
        let serverSelected = selectedServerLocalDefinitionID.flatMap { id in
            fineTuning.variants.first { $0.id == id }
        }
        guard let record = serverSelected ?? selectedSteeringVariant else {
            cluster.activity = "select a local variant first"
            return
        }
        do {
            cluster.activity = "uploading variant..."
            let uploaded = try await client.uploadVariant(record.artifact)
            cluster.remoteVariants = try await client.variants()
            selectedRemoteModelID = uploaded.variant.baseModelID
            selectedRemoteVariantPath = uploaded.path
            selectedRemoteVariantHash = uploaded.hash
            // The stored copy is now the selection (path identity).
            selectedServerLocalDefinitionID = nil
            let missing = uploaded.missingArtifacts.count
            cluster.activity = missing == 0
                ? "uploaded variant \(uploaded.variant.name)"
                : "uploaded variant, but \(missing) referenced artifact(s) are missing on server"
        } catch {
            cluster.activity = "variant upload failed: \(error)"
        }
    }

    private func runRemoteGeneration(prompt: String, continuation: Bool = false) async {
        defer {
            isGenerating = false
            generationTask = nil
            // Error/stop exits: the stream's "loading…" caption must not
            // outlive the generation it described (the success path already
            // replaced it and cleared the flag).
            if serverStreamStatusShown {
                cluster.activity = nil
                serverStreamStatusShown = false
            }
        }
        guard let client = cluster.client else {
            errorMessage = "invalid server URL"
            return
        }
        // Ordinary send: the full transcript minus the empty assistant turn
        // we just appended, so the server sees the conversation, not just the
        // latest user message. Continuation: the full transcript INCLUDING
        // the final seeded assistant prefix the server will continue.
        let messages = Self.wireMessages(
            from: continuation ? transcript : Array(transcript.dropLast()))
        // Capability re-gate at send time (the seed gate ran earlier, but the
        // active server can change between seeding and sending): a transcript
        // carrying seeded turns must never be sent to a server that would
        // silently mis-handle them.
        if messages.contains(where: { $0.seeded == true }),
            cluster.capabilities?.supportsSeededChatTurns != true
        {
            errorMessage = "this server does not support seeded assistant "
                + "turns (no chat.seededTurns capability) — the transcript "
                + "contains seeded turns, so this send was refused"
            return
        }
        if continuation,
            cluster.capabilities?.supportsAssistantPrefillContinuation != true
        {
            errorMessage = "this server does not support assistant-prefix "
                + "continuation (no chat.continueFinalMessage capability)"
            return
        }
        // Honest composition: a slot that doesn't resolve against the server
        // catalog is dropped from the spec (a local path must never reach the
        // server) — but never silently. Refresh the catalog once to close the
        // staleness window (new vector not yet listed, failed earlier fetch),
        // re-resolve, and surface whatever still drops as a persistent error.
        var resolution = serverControlResolution()
        if !resolution.unresolvedVectorIDs.isEmpty {
            await catalog.refreshRemoteVectors()
            resolution = serverControlResolution()
        }
        var sendWarnings: [String] = []
        if let warning = InlineVariantComposer.unresolvedSendWarning(
            unresolvedVectorIDs: resolution.unresolvedVectorIDs)
        {
            sendWarnings.append(warning)
        }
        let currentControls = resolution.state
        let disposition = InlineVariantComposer.disposition(
            storedVariantSelected: selectedRemoteVariantPath?.isEmpty == false,
            seeded: seededServerControlState,
            current: currentControls)
        // Stored-variant shadow: with an unseedable spec, disposition stays
        // .storedVariant no matter what the rows say — configured vectors
        // silently never ride. Say so on EVERY such send, not only in the
        // send-mode caption.
        if disposition == .storedVariant,
            let warning = InlineVariantComposer.unseededStoredVariantWarning(
                storedVariantSelected: selectedRemoteVariantPath?.isEmpty == false,
                seeded: seededServerControlState != nil,
                configuredSlotCount: activeSlotCount)
        {
            sendWarnings.append(warning)
        }
        if !sendWarnings.isEmpty {
            errorMessage = sendWarnings.joined(separator: "; ")
        }
        // The done event's provenance stamp is authoritative when it arrives;
        // this closure records it for the transcript metadata.
        let recordMetadata: @Sendable ([String: JSONValue]) async -> Void =
            { [weak self] metadata in
                await MainActor.run {
                    self?.lastServerVariantProvenance =
                        Self.serverVariantProvenance(from: metadata)
                }
            }
        // Pre-token server progress ("model X is not loaded yet — loading it
        // now…") lands in the status line: without it, an on-demand cold load
        // on the worker is minutes of spinner with no explanation.
        serverStreamStatusShown = false
        let showStatus: @Sendable (String) async -> Void = { [weak self] status in
            await MainActor.run {
                self?.cluster.activity = status
                self?.serverStreamStatusShown = true
            }
        }
        do {
            switch disposition {
            case .storedVariant:
                guard let variantPath = selectedRemoteVariantPath, !variantPath.isEmpty
                else { return }
                // Refresh-on-send: the server's variant chat rejects hash
                // drift (variant_chat.load_variant) — right for studies,
                // brittle for exploration, where a re-saved server variant
                // would fail every send until the client re-pins. Re-check
                // the artifact before sending; the server stays strict.
                if let liveVariants = try? await client.variants() {
                    cluster.remoteVariants = liveVariants
                    guard liveVariants.contains(where: { $0.path == variantPath }) else {
                        errorMessage =
                            "server variant no longer exists (\(variantPath)); "
                            + "re-select or re-upload it"
                        return
                    }
                    if let pinned = selectedRemoteVariantHash,
                        let liveHash = try? await client.variantArtifactHash(path: variantPath),
                        liveHash != pinned
                    {
                        selectedRemoteVariantHash = liveHash
                        cluster.activity =
                            "server variant was re-saved; using the latest version"
                    }
                }
                lastServerVariantProvenance = "stored variant \(variantPath)"
                    + (selectedRemoteVariantHash.map { " (hash \($0.prefix(12)))" } ?? "")
                try await client.streamVariantChat(
                    selection: .stored(path: variantPath, hash: selectedRemoteVariantHash),
                    messages: messages,
                    maxTokens: maxTokens,
                    temperature: temperature,
                    promptMode: promptMode.rawValue,
                    systemPrompt: nilIfEmpty(systemPrompt),
                    stripInterventions: stripRemoteVariantInterventions,
                    continueFinalMessage: continuation,
                    onMetadata: recordMetadata,
                    onStatus: showStatus
                ) { [weak self] chunk in
                    await MainActor.run {
                        guard let self, let last = self.transcript.indices.last else { return }
                        self.transcript[last].text += chunk
                    }
                }

            case .inlineVariant:
                // Edited (or from-scratch) controls: compose an ephemeral spec
                // — the server stamps `source: "inline"` with no path/hash, so
                // this send never claims a stored variant's identity.
                guard let model = selectedRemoteModelID, !model.isEmpty else {
                    errorMessage =
                        "select a server model first — the inline variant spec "
                        + "pins its base model"
                    return
                }
                let spec = InlineVariantComposer.compose(currentControls)
                lastServerVariantProvenance = "inline (source: inline — not a stored variant)"
                try await client.streamVariantChat(
                    selection: .inline(spec),
                    messages: messages,
                    maxTokens: maxTokens,
                    temperature: temperature,
                    promptMode: promptMode.rawValue,
                    systemPrompt: nilIfEmpty(systemPrompt),
                    stripInterventions: stripRemoteVariantInterventions,
                    continueFinalMessage: continuation,
                    onMetadata: recordMetadata,
                    onStatus: showStatus
                ) { [weak self] chunk in
                    await MainActor.run {
                        guard let self, let last = self.transcript.indices.last else { return }
                        self.transcript[last].text += chunk
                    }
                }

            case .plainGenerate:
                lastServerVariantProvenance = nil
                try await client.streamGenerate(
                    text: prompt,
                    messages: messages,
                    maxTokens: maxTokens,
                    temperature: temperature,
                    promptMode: promptMode.rawValue,
                    systemPrompt: nilIfEmpty(systemPrompt),
                    qwenThinkingEnabled: qwenThinkingEnabled,
                    continueFinalMessage: continuation
                ) { [weak self] chunk in
                    await MainActor.run {
                        guard let self, let last = self.transcript.indices.last else { return }
                        self.transcript[last].text += chunk
                    }
                }
            }
            // The status line must not keep saying "loading…" after the
            // answer arrived (engineer review 2026-07-17): replace the
            // stream's caption with a terminal one on completion.
            if serverStreamStatusShown {
                cluster.activity = "response complete"
                serverStreamStatusShown = false
            }
            cluster.remoteState = try? await client.state()
        } catch is CancellationError {
            // user pressed Stop
        } catch let error as ClusterClient.ClientError {
            // The controller's 409 "no GPU session" refusal carries its own
            // next step — surface it with the pointer at the session control
            // instead of a generic failure line.
            if case .badResponse(let code, let body) = error,
                let hint = GPUSessionRefusal.hint(code: code, body: body)
            {
                errorMessage = hint
                return
            }
            // Surface the server's self-naming refusal (FastAPI `detail`, or
            // the in-band SSE error) verbatim — e.g. "variant 'chat-inline'
            // uses residual-norm alpha but vector arousal has no residual
            // norms" must reach the user unhidden.
            errorMessage = "remote generation failed: "
                + ClusterClient.unwrappingDetail(error).description
        } catch {
            // Stop cancels the URLSession task, which throws
            // URLError(.cancelled), not CancellationError — a stop is a stop,
            // never a red banner.
            if Self.isCancellation(error) { return }
            errorMessage = "remote generation failed: \(error.localizedDescription)"
        }
    }

    /// True for every shape a user-initiated Stop arrives in: structured-
    /// concurrency cancellation, URLSession task cancellation, or either
    /// wrapped in an NSError.
    static func isCancellation(_ error: Error) -> Bool {
        if error is CancellationError { return true }
        if let urlError = error as? URLError, urlError.code == .cancelled {
            return true
        }
        let nsError = error as NSError
        return nsError.domain == NSURLErrorDomain
            && nsError.code == NSURLErrorCancelled
    }

    private func runGeneration(prompt: String) async {
        defer {
            isGenerating = false
            generationTask = nil
        }
        lastServerVariantProvenance = nil  // local turn: server stamp is stale
        guard let container else { return }
        var activeAdapter: LoRAContainer?
        defer {
            if let activeAdapter {
                Task { await self.unloadAdapter(activeAdapter, from: container) }
            }
        }
        do {
            await refreshLocalContextEstimateIfNeeded(prefixCount: transcript.count - 2)
            activeAdapter = try await applyCurrentAdapter(to: container)
            switch promptMode {
            case .rawCompletion:
                let output = try await ExperimentTasks.generate(
                    container,
                    prompt: prompt,
                    modelID: selectedModelID,
                    maxTokens: maxTokens,
                    temperature: temperature,
                    injections: try currentInjections(),
                    promptMode: .rawCompletion,
                    systemPrompt: nilIfEmpty(systemPrompt),
                    qwenThinkingEnabled: qwenThinkingEnabled
                ) { [weak self] output in
                    await MainActor.run {
                        guard let self, let last = self.transcript.indices.last else { return }
                        self.transcript[last].text = output
                    }
                }
                if let last = transcript.indices.last, transcript[last].text.isEmpty {
                    transcript[last].text = output
                }

            case .chatAssistant:
                if prompt.count >= Self.longPromptStudyPathCharacterThreshold {
                    errorMessage =
                        "long prompt: using standalone chunked generation for this turn "
                        + "to avoid oversized chat-session prefill"
                    let output = try await ExperimentTasks.generate(
                        container,
                        prompt: prompt,
                        modelID: selectedModelID,
                        maxTokens: maxTokens,
                        temperature: temperature,
                        injections: try currentInjections(),
                        promptMode: .chatAssistant,
                        systemPrompt: nilIfEmpty(systemPrompt),
                        qwenThinkingEnabled: qwenThinkingEnabled
                    ) { [weak self] output in
                        await MainActor.run {
                            guard let self, let last = self.transcript.indices.last else { return }
                            self.transcript[last].text = output
                        }
                    }
                    if let last = transcript.indices.last, transcript[last].text.isEmpty {
                        transcript[last].text = output
                    }
                    if errorMessage?.hasPrefix("long prompt:") == true {
                        errorMessage = nil
                    }
                    chatContextTokenEstimate = 0
                    startSession()
                    return
                }
                // A seeded assistant turn (or an out-of-session continuation)
                // diverged the transcript from the ChatSession's KV history:
                // rebuild the session from the transcript so this turn
                // replays the seeded history through the model's own chat
                // template — the seeded turn reaches the model in the real
                // assistant format, indistinguishable from a generated one.
                if pendingSeededHistoryReplay {
                    startSession(replayingTranscriptUpTo: transcript.count - 2)
                }
                guard let session else { return }
                let turnPromptTokens = try await ExperimentTasks.preparedPromptTokenCount(
                    container,
                    prompt: prompt,
                    modelID: selectedModelID,
                    promptMode: .chatAssistant,
                    systemPrompt: nilIfEmpty(systemPrompt),
                    qwenThinkingEnabled: qwenThinkingEnabled)
                try await ExperimentTasks.validateContextBudget(
                    container,
                    modelID: selectedModelID,
                    promptTokens: chatContextTokenEstimate + turnPromptTokens,
                    requestedGenerationTokens: maxTokens)
                let probeSpecs = probeHighlightsEnabled ? try currentProbeSpecs() : []
                let recorder = probeSpecs.isEmpty
                    ? nil
                    : ActivationRecorder(layers: Set(probeSpecs.map(\.layer)))
                if probeHighlightsEnabled {
                    probeStatus = probeSpecs.isEmpty
                        ? "probe enabled, but no enabled vectors to score"
                        : (selectedReadingProbe == nil ? "vector cosine probe" : "trained probe")
                            + " armed on layer\(Set(probeSpecs.map(\.layer)).count == 1 ? "" : "s") "
                            + Set(probeSpecs.map(\.layer)).sorted().map(String.init)
                            .joined(separator: ", ")
                }
                try await applyCurrentSteering(to: container, recorder: recorder)
                // ChatSession hides the rendered prompt's token count, so the
                // injectors can't gate on the prompt end across prefill chunks.
                // Instead, guarantee single-chunk prefill: with one prefill
                // pass, "last position of the pass" IS the prompt end. 32k
                // covers any chat prompt within these models' context windows.
                session.generateParameters = GenerateParameters(
                    maxTokens: maxTokens, temperature: Float(temperature),
                    prefillStepSize: 32768)
                let stream = session.streamResponse(to: chatPrompt(prompt))
                var nextCaptureIndex = recorder?.captures.count ?? 0
                var pendingProbeScores: [Float] = []
                var lastMeasuredScore: Float?
                let usesCalibratedProbe = selectedReadingProbe != nil
                for try await chunk in stream {
                    if Task.isCancelled { break }
                    if let last = transcript.indices.last {
                        transcript[last].text += chunk
                        if let recorder {
                            let captures = recorder.captures
                            let newCaptures = Array(captures.dropFirst(nextCaptureIndex))
                                .filter { $0.offset > 0 }
                            nextCaptureIndex = captures.count
                            pendingProbeScores.append(
                                contentsOf: probeScoresByOffset(
                                    captures: newCaptures, specs: probeSpecs))
                            let score: Float?
                            let statusPrefix: String
                            if pendingProbeScores.isEmpty {
                                score = lastMeasuredScore
                                statusPrefix = score == nil
                                    ? "latest chunk had no score"
                                    : "carried score "
                            } else {
                                score = pendingProbeScores.removeFirst()
                                lastMeasuredScore = score
                                statusPrefix = "last score "
                            }
                            let opacity = score.map {
                                probeHighlightOpacity(
                                    score: $0, calibrated: usesCalibratedProbe)
                            } ?? 0
                            transcript[last].probeSpans.append(
                                ProbeSpan(text: chunk, score: score, opacity: opacity))
                            probeStatus =
                                "probe spans \(transcript[last].probeSpans.count), captures \(captures.count), queued \(pendingProbeScores.count), "
                                + (score.map {
                                    statusPrefix
                                        + $0.formatted(.number.precision(.fractionLength(3)))
                                } ?? statusPrefix)
                        }
                    }
                }
                let responseText = transcript.last?.text ?? ""
                let responseTokens = await tokenCount(responseText, in: container)
                chatContextTokenEstimate += turnPromptTokens + responseTokens
            }
        } catch is CancellationError {
            // user pressed Stop — not an error
        } catch {
            if Self.isCancellation(error) { return }
            errorMessage = "generation failed: \(error)"
        }
    }

    // MARK: - Steering plumbing

    private func applyCurrentAdapter(to container: ModelContainer) async throws -> LoRAContainer? {
        guard adaptersEnabled,
            let record = selectedRuntimeAdapter
        else { return nil }
        guard record.artifact.baseModelID == loadedModelID else {
            throw ChatServiceError(
                reason: "adapter \(record.artifact.name) belongs to \(record.artifact.baseModelID), "
                    + "not the loaded model")
        }
        // Substrate gate: an explicitly foreign-stamped adapter (hf-peft-lora
        // weights) must never be loaded into the MLX model — the picker
        // already excludes them, but a stale selection must fail loudly too.
        if let refusal = AdapterSubstrateGate.refusalMessage(
            name: record.artifact.name,
            substrate: record.artifact.substrate,
            adapterFormat: record.artifact.adapterFormat)
        {
            throw ChatServiceError(reason: refusal)
        }
        let directory = FineTuneStore.absoluteURL(record.artifact.adapterDirectory)
        let adapter = try LoRAContainer.from(directory: directory)
        try await container.perform { context in
            try adapter.load(into: context.model)
        }
        return adapter
    }

    private func unloadAdapter(_ adapter: LoRAContainer, from container: ModelContainer) async {
        await container.perform { context in
            adapter.unload(from: context.model)
        }
    }

    private func conceptVectors(for artifact: VectorArtifact) throws -> ConceptVectors {
        if let cached = vectorCache[artifact.id] { return cached }
        let (loaded, _) = try SteeringVectorStore.load(
            from: artifact.directory, name: artifact.name)
        vectorCache[artifact.id] = loaded
        return loaded
    }

    /// The artifact's stored per-layer neutral residual mean, cached like
    /// `conceptVectors(for:)`. `.some(nil)` caches "artifact has none" so
    /// legacy artifacts don't re-read the sidecar every send.
    private func neutralMean(for artifact: VectorArtifact) throws -> [[Float]]? {
        if let cached = neutralMeanCache[artifact.id] { return cached }
        let loaded = try SteeringVectorStore.loadNeutralMean(
            from: artifact.directory, name: artifact.name)
        neutralMeanCache[artifact.id] = loaded
        return loaded
    }

