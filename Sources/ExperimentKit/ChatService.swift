    public init(cluster: ClusterConnectionStore, catalog: SubstrateCatalog? = nil) {
        self.cluster = cluster
        // Headless hosts (web server, tests) may not pass a shared catalog;
        // the app creates one instance and injects it everywhere.
        self.catalog = catalog ?? SubstrateCatalog(store: cluster)
        self.selectedModelID = Self.availableModels[0].id
        concepts.host = self
        experiments.host = self
        fineTuning.host = self
        multiAgent.host = self
        geometry.host = self
        optvec.host = self
        // F4: after a successful same-machine auto-switch the store has
        // already reconnected — the coordinator's ONLY extra step is this
        // artifact refresh (vector catalog + adapters + stored agents).
        cluster.workspaceSyncArtifactRefresh = { [weak self] in
            await self?.refreshServerSteeringArtifacts()
        }
        // A finished install is exactly the moment the installed-models index
        // is stale: re-scan so the picker's availability and the Load gate
        // both see the new weights without a relaunch. The rescan also drops
        // the judge-capability memo (see `refreshLocalInstalledModels`), so a
        // repo that was "no cached snapshot" a minute ago is re-inspected
        // rather than remembered as un-judgeable for the session.
        modelInstaller.onFinished = { [weak self] _ in
            self?.catalog.refreshLocalInstalledModels()
        }
        refreshVectors()
    }

