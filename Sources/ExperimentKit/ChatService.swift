    public func injectionPreview(for slot: SteerSlot) -> InjectionPreview? {
        // No preview for ablate rows: the Δnorm math below (|α|·‖v‖, norm-unit
        // conversion) describes an ADDITIVE injection; ablation removes a
        // fraction of whatever the stream contains, so any number here would
        // be an invented claim. The λ controls carry their own copy.
        guard slot.mode != .ablate else { return nil }
        guard let artifact = artifact(for: slot),
            let vectors = try? conceptVectors(for: artifact)
        else { return nil }
        let layer = min(
            max(0, artifact.fixedSteeringLayer ?? Int(slot.layer)),
            vectors.layerCount - 1)
        let vector = projectedSteeringVector(vectors.perLayer[layer], layer: layer)
        return InjectionPreview.compute(
            layer: layer,
            vectorNorm: SteeringVectorMath.l2Norm(vector),
            residualNorm: artifact.sidecar.residualNormPerLayer?[safe: layer],
            alpha: slot.alpha,
            alphaInNormUnits: alphaInNormUnits,
            fixedLayer: artifact.fixedSteeringLayer != nil)
    }

    /// Server-slot twin of `injectionPreview`: same struct, same math
    /// (`InjectionPreview.compute`), fed from the catalog's per-layer norm
    /// tables instead of loaded vector bytes. Nil when the record (or an
    /// older server's catalog) carries no `normsPerLayer` — no invented
    /// numbers. The preview is an estimate of the server-side injection: the
    /// server converts from its own sidecar, and neutral-direction projection
    /// (not available server-side) never applies.
    public func serverInjectionPreview(for slot: SteerSlot) -> InjectionPreview? {
        // Same rule as `injectionPreview`: additive-injection math only.
        guard slot.mode != .ablate else { return nil }
        guard let record = serverVectorRecord(for: slot),
            let norms = record.normsPerLayer
        else { return nil }
        let layer = min(max(0, Int(slot.layer)), max(0, record.layerCount - 1))
        guard let vectorNorm = norms[safe: layer] else { return nil }
        return InjectionPreview.compute(
            layer: layer,
            vectorNorm: vectorNorm,
            residualNorm: record.residualNormPerLayer?[safe: layer],
            alpha: slot.alpha,
            alphaInNormUnits: alphaInNormUnits,
            fixedLayer: false)
    }

