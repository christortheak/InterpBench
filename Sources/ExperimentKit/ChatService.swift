    /// nil = selectable. A server-stored agent is excluded (disabled, with
    /// this reason) only when the server's inventory is KNOWN and does not
    /// contain its base model — an unknown/empty inventory (not yet
    /// connected) never invents exclusions. A base model that IS installed
    /// but differs from the current model selection stays selectable:
    /// selecting the agent seeds its own base model, exactly like the Agents
    /// tab's "Use in Chat".
    nonisolated public static func serverAgentExclusion(
        baseModelID: String, installedServerModels: [String]
    ) -> String? {
        guard !installedServerModels.isEmpty,
            !installedServerModels.contains(baseModelID)
        else { return nil }
        return "built for \(baseModelID) — not installed on this server"
    }

