    /// Follow a durable server job into the shared live-log display (the
    /// Activity pane): stream its log lines under `title`, then resolve the
    /// terminal record — the public twin of `ConceptBuilder`'s private
    /// follower, for surfaces without a builder (e.g. the Analysis panel's
    /// server Gemma Scope run). Returns nil when the job is still running at
    /// the poll timeout or the surrounding task was cancelled; the job keeps
    /// running server-side either way.
    public func followServerJobInActivity(
        jobID: String,
        client: ClusterClient,
        title: String,
        maxLines: Int = 400,
        pollTimeout: TimeInterval = 600
    ) async -> RemoteJobRecord? {
        var lines = ["queued job \(jobID)"]
        let logID = startLiveLog(title: title, initialLine: lines[0])

        do {
            try await client.streamJobLog(jobID: jobID) { line in
                await MainActor.run {
                    lines.append(line)
                    if lines.count > maxLines {
                        lines.removeFirst(lines.count - maxLines)
                    }
                    self.updateLiveLog(id: logID, title: title, lines: lines)
                }
            }
        } catch is CancellationError {
            return nil
        } catch {
            lines.append("log stream ended: \(error.localizedDescription)")
            updateLiveLog(id: logID, title: title, lines: lines)
        }

        // The SSE stream closes at a terminal state in the common case; a
        // broken stream falls back to polling until terminal or timeout.
        let terminal: Set<String> = ["succeeded", "failed", "cancelled"]
        let deadline = Date().addingTimeInterval(pollTimeout)
        while !Task.isCancelled {
            if let job = try? await client.job(jobID),
                terminal.contains(job.status) || job.finishedAt != nil
            {
                lines.append("job \(job.status)")
                if let error = job.error, !error.isEmpty {
                    lines.append(error)
                }
                updateLiveLog(id: logID, title: title, lines: lines)
                return job
            }
            guard Date() < deadline else { return nil }
            try? await Task.sleep(for: .seconds(2))
        }
        return nil
    }

