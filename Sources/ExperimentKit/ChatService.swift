    /// Effective raw alpha at a layer: raw, or converted so the injected
    /// perturbation's L2 norm is alpha × the layer's typical residual norm
    /// (the vector's own norm is folded out — see normUnitScale).
    private func effectiveAlpha(
        _ alpha: Double, at index: Int, sidecar: SteeringVectorSidecar,
        vectorNorm: Float
    ) throws -> Float {
        guard alphaInNormUnits else { return Float(alpha) }
        guard let norms = sidecar.residualNormPerLayer, norms.indices.contains(index) else {
            throw ChatServiceError(
                reason: "vector for \(sidecar.concept) has no residual norms — "
                    + "measure them in \(SteeringGuidance.normBackfillLocation), "
                    + "or switch α to raw")
        }
        do {
            return try SteeringVectorMath.normUnitScale(
                alpha: Float(alpha), residualNorm: norms[index], vectorNorm: vectorNorm)
        } catch {
            throw ChatServiceError(
                reason: "vector for \(sidecar.concept) is degenerate at layer \(index) "
                    + "(zero norm) — cannot express alpha in norm units")
        }
    }

    // MARK: Slot-injection honesty (no steering row may silently inject nothing)

    /// The cheap facts about one steering row that decide whether its
    /// injection can actually be applied. Gathered per substrate (local:
    /// loaded artifact bytes; server: catalog record) and fed to the ONE
    /// pure rule below, so the send-time refusal and the standing per-row
    /// caption can never drift apart.
    public struct SlotInjectionFacts: Sendable, Equatable {
        /// nil ⇔ the row's vector id did not resolve to an artifact.
        public var concept: String?
        public var vectorModelID: String?
        public var loadedModelID: String?
        public var alphaInNormUnits: Bool
        /// Residual-norm denominators at the band layers this row would
        /// inject into. nil = the sidecar records none at all; an entry ≤ 0
        /// is a degenerate denominator.
        public var residualNormsAtBandLayers: [Float]?
        /// Post-projection vector L2 norms at the band layers.
        public var vectorNormsAtBandLayers: [Float]
        public var neutralProjectionActive: Bool
        /// True for an ablate row. λ is a plain fraction of what is present —
        /// it never converts through the residual-norm denominator, so the
        /// norm-units checks below do not apply to ablation (the injection
        /// builders on both engines already bypass the conversion; the
        /// refusal rule must agree or it refuses a send the engine would run).
        public var isAblation: Bool

        public init(
            concept: String?,
            vectorModelID: String? = nil,
            loadedModelID: String? = nil,
            alphaInNormUnits: Bool = false,
            residualNormsAtBandLayers: [Float]? = nil,
            vectorNormsAtBandLayers: [Float] = [],
            neutralProjectionActive: Bool = false,
            isAblation: Bool = false
        ) {
            self.concept = concept
            self.vectorModelID = vectorModelID
            self.loadedModelID = loadedModelID
            self.alphaInNormUnits = alphaInNormUnits
            self.residualNormsAtBandLayers = residualNormsAtBandLayers
            self.vectorNormsAtBandLayers = vectorNormsAtBandLayers
            self.neutralProjectionActive = neutralProjectionActive
            self.isAblation = isAblation
        }
    }

    /// Why this row will NOT inject — nil when it will. Pure so it is
    /// unit-testable without a model. The send path treats a non-nil result
    /// as a REFUSAL (the generation must not silently run with less steering
    /// than the rows claim — the classic silent-failure class); the steering
    /// UI shows the same string as a standing caption before any send.
    public nonisolated static func slotInjectionRefusal(
        _ facts: SlotInjectionFacts
    ) -> String? {
        guard let concept = facts.concept else {
            return "NOT injected: this row's vector does not resolve to an "
                + "artifact — press Refresh artifacts or re-pick the vector"
        }
        if let vectorModel = facts.vectorModelID, vectorModel != facts.loadedModelID {
            return "NOT injected: vector for \(concept) was extracted from "
                + "\(vectorModel), not the loaded model"
        }
        if !facts.vectorNormsAtBandLayers.isEmpty,
            facts.vectorNormsAtBandLayers.allSatisfy({ !($0 > 0) })
        {
            return facts.neutralProjectionActive
                ? "NOT injected: neutral-direction projection removes all of "
                    + "'\(concept)' at the selected layer band — turn off Remove "
                    + "neutral directions or pick another basis/layer"
                : "NOT injected: '\(concept)' has zero norm across the selected "
                    + "layer band — the artifact is degenerate there; pick "
                    + "another layer"
        }
        if facts.alphaInNormUnits, !facts.isAblation {
            // Ablation is exempt by design, not by oversight: λ never
            // converts through the denominator, so a norms-less vector
            // ablates fine — refusing here dead-ended every J-lens ablation
            // (field report 2026-08-06).
            guard let norms = facts.residualNormsAtBandLayers else {
                return "NOT injected: α is in residual-norm units but "
                    + "'\(concept)' has no residual norms — measure them in "
                    + "\(SteeringGuidance.normBackfillLocation), or switch α to raw"
            }
            if norms.contains(where: { !($0 > 0) }) {
                return "NOT injected: '\(concept)' has no usable residual-norm "
                    + "denominator in the selected layer band — measure norms in "
                    + "\(SteeringGuidance.normBackfillLocation), or switch α to raw"
            }
        }
        return nil
    }

    /// Server-workspace twin of `slotInjectionRefusal`, from catalog facts:
    /// the injection runs server-side, so this predicts what the server's
    /// `variant_injections` will refuse (missing/degenerate residual norms
    /// under norm-unit alpha) or what composition will drop (unresolved id).
    /// nil when the row rides — or when an older catalog reports too little
    /// to know (no invented refusals).
    public nonisolated static func serverSlotRefusal(
        concept: String?,
        alphaInNormUnits: Bool,
        residualNormPerLayer: [Float]?,
        hasResidualNorms: Bool?,
        layer: Int,
        isAblation: Bool = false
    ) -> String? {
        guard let concept else {
            return "NOT sent: this row does not resolve in the server catalog "
                + "listing — press Refresh artifacts or re-pick the vector"
        }
        // The server's `variant_injections` never converts λ through the
        // residual-norm denominator, so an ablate row on a norms-less vector
        // runs fine — predicting a refusal here would be false.
        guard alphaInNormUnits, !isAblation else { return nil }
        if let norms = residualNormPerLayer {
            let index = min(max(0, layer), max(0, norms.count - 1))
            guard norms.indices.contains(index), norms[index] > 0 else {
                return "server will refuse this send: '\(concept)' has no usable "
                    + "residual-norm denominator at L\(index) — measure norms in "
                    + "\(SteeringGuidance.normBackfillLocation), or switch α to raw"
            }
            return nil
        }
        if hasResidualNorms == false {
            return "server will refuse this send: '\(concept)' has no residual "
                + "norms — measure them in \(SteeringGuidance.normBackfillLocation), "
                + "or switch α to raw"
        }
        return nil  // older catalog: unknown, not assumed broken
    }

    /// Standing per-row caption for the steering controls: the reason this
    /// row will NOT be applied on the next send, or nil when it will (or when
    /// the row is off/empty — an intentionally idle row needs no warning).
    public func slotNotAppliedCaption(for slot: SteerSlot) -> String? {
        guard steeringEnabled, slot.enabled, slot.vectorID != nil else { return nil }
        if isServerWorkspace {
            let record = serverVectorRecord(for: slot)
            let layer = min(
                max(0, Int(slot.layer)), max(0, (record?.layerCount ?? 1) - 1))
            return Self.serverSlotRefusal(
                concept: serverSlotConcept(for: slot),
                alphaInNormUnits: alphaInNormUnits,
                residualNormPerLayer: record?.residualNormPerLayer,
                hasResidualNorms: record?.hasResidualNorms,
                layer: layer,
                isAblation: slot.mode == .ablate)
        }
        guard let artifact = artifact(for: slot) else {
            return Self.slotInjectionRefusal(SlotInjectionFacts(concept: nil))
        }
        guard let facts = try? slotInjectionFacts(for: slot, artifact: artifact) else {
            return "NOT injected: could not load '\(artifact.sidecar.concept)' "
                + "from \(artifact.directory.lastPathComponent)"
        }
        return Self.slotInjectionRefusal(facts)
    }

    /// The band layers a slot injects into (fixed-layer artifacts pin the
    /// band to width 1) and the facts the refusal rule needs — one gatherer
    /// shared by the caption and the send so they see the same numbers.
    private func slotInjectionFacts(
        for slot: SteerSlot, artifact: VectorArtifact
    ) throws -> SlotInjectionFacts {
        let conceptVectors = try conceptVectors(for: artifact)
        let isAblation = slot.mode == .ablate
        // Same band rule as `currentInjections`: ablation covers the whole
        // network, so its facts (vector norms) must be gathered there too.
        let band = isAblation
            ? Array(0..<conceptVectors.layerCount)
            : Self.bandLayers(
                center: artifact.fixedSteeringLayer ?? Int(slot.layer),
                layerCount: conceptVectors.layerCount,
                bandWidth: artifact.fixedSteeringLayer == nil ? layerBandWidth : 1)
        let projectionActive =
            removeNeutralDirectionsAtSteering && selectedNeutralPCBasis != nil
        let vectorNorms = band.map { index in
            SteeringVectorMath.l2Norm(
                projectedSteeringVector(conceptVectors.perLayer[index], layer: index))
        }
        let residualNorms = artifact.sidecar.residualNormPerLayer.map { norms in
            band.map { index -> Float in norms[safe: index] ?? 0 }
        }
        return SlotInjectionFacts(
            concept: artifact.sidecar.concept,
            vectorModelID: artifact.sidecar.modelID,
            loadedModelID: loadedModelID,
            alphaInNormUnits: alphaInNormUnits,
            residualNormsAtBandLayers: residualNorms,
            vectorNormsAtBandLayers: vectorNorms,
            neutralProjectionActive: projectionActive,
            isAblation: isAblation)
    }

    /// Clamped inclusive band around `center` — the one band rule for facts
    /// gathering and injection building (they must agree layer-for-layer).
    nonisolated static func bandLayers(
        center: Int, layerCount: Int, bandWidth: Int
    ) -> [Int] {
        let clampedCenter = min(max(0, center), max(0, layerCount - 1))
        let halfWidth = max(0, (bandWidth - 1) / 2)
        let lower = max(0, clampedCenter - halfWidth)
        let upper = min(max(0, layerCount - 1), clampedCenter + halfWidth)
        return Array(lower ... upper)
    }

    /// Builds one injector per (slot, band layer). Injectors compose
    /// additively in the residual stream, so multiple slots ARE the linear
    /// combination h + Σ αᵢ·vᵢ.
    private func applyCurrentSteering(
        to container: ModelContainer,
        recorder: ActivationRecorder? = nil
    ) async throws {
        var interventions = try InterventionPlan.interventions(
            try currentInjections().map(\.planEdit))
        if let recorder {
            interventions.append(recorder)
        }
        let toApply = interventions
        try await container.perform { context in
            guard let model = context.model as? InterventionHookable else {
                throw ChatServiceError(reason: "loaded model has no intervention hooks")
            }
            model.interventions = toApply
        }
    }

    /// Builds the summed injection list from all enabled rows. HONEST
    /// assembly: a row that looks active in the UI but cannot inject —
    /// unresolved vector, wrong model, zero norm across its whole band,
    /// norm-unit alpha without a denominator — REFUSES the send with the
    /// row's self-naming reason (`slotInjectionRefusal`) instead of silently
    /// steering with less than the controls claim. Zero-norm layers inside
    /// an otherwise nonzero band are the only skip, and only because the
    /// band's remaining layers still inject what the row promises.
    private func currentInjections() throws -> [ExperimentTasks.CellInjection] {
        guard steeringEnabled else { return [] }
        ablationAdvisory = nil  // stale advice is worse than none
        var injections: [ExperimentTasks.CellInjection] = []
        for slot in slots where slot.enabled {
            guard slot.vectorID != nil else { continue }  // idle row, nothing claimed
            guard let artifact = artifact(for: slot) else {
                throw ChatServiceError(
                    reason: Self.slotInjectionRefusal(SlotInjectionFacts(concept: nil))
                        ?? "steering row does not resolve to a vector artifact")
            }
            let facts = try slotInjectionFacts(for: slot, artifact: artifact)
            if let refusal = Self.slotInjectionRefusal(facts) {
                throw ChatServiceError(reason: refusal)
            }
            let conceptVectors = try conceptVectors(for: artifact)
            let isAblation = slot.mode == .ablate
            // Ablation covers the whole network: removing a direction at one
            // layer is usually undone by the layers above it. Steering keeps
            // its declared layer widened by the session's band.
            let band = isAblation
                ? Array(0..<conceptVectors.layerCount)
                : Self.bandLayers(
                    center: artifact.fixedSteeringLayer ?? Int(slot.layer),
                    layerCount: conceptVectors.layerCount,
                    bandWidth: artifact.fixedSteeringLayer == nil ? layerBandWidth : 1)
            // Neutral-mean centering of the ablation direction (see
            // `centerAblationAgainstNeutralMean`). Never silent either way:
            // centering-unavailable and high-alignment-uncentered both set
            // `ablationAdvisory`, which the ablation controls display.
            var ablationMean: [[Float]]?
            if isAblation {
                let stored = try neutralMean(for: artifact)
                if centerAblationAgainstNeutralMean {
                    ablationMean = stored
                    if stored == nil {
                        ablationAdvisory = ExperimentTasks.reportAblationMeanAlignment(
                            concept: artifact.sidecar.concept,
                            vectors: [], firstLayer: 0, neutralMean: nil,
                            where: "playground",
                            remedy: "re-extract the concept with a neutral corpus")
                    }
                } else {
                    ablationAdvisory = ExperimentTasks.reportAblationMeanAlignment(
                        concept: artifact.sidecar.concept,
                        vectors: band.map { conceptVectors.perLayer[$0] },
                        firstLayer: 0,
                        neutralMean: stored,
                        where: "playground",
                        remedy: "enable ablation mean-centering")
                }
            }
            for index in band {
                let raw = conceptVectors.perLayer[index]
                let centered = ablationMean.map {
                    SteeringVectorMath.meanCentered(raw, against: $0[index])
                }
                let vector = projectedSteeringVector(centered ?? raw, layer: index)
                let vectorNorm = SteeringVectorMath.l2Norm(vector)
                guard vectorNorm > 0 else { continue }  // band edge; rest injects
                injections.append(
                    ExperimentTasks.CellInjection(
                        layer: index,
                        vector: vector,
                        // λ is NOT scaled by the residual norm. That
                        // denominator exists to make α comparable across
                        // concepts and layers; ablation removes whatever is
                        // present, so it is already self-scaling and putting
                        // it through the conversion would silently change how
                        // much gets removed.
                        alpha: isAblation
                            ? Float(slot.alpha)
                            : try effectiveAlpha(
                                slot.alpha, at: index, sidecar: artifact.sidecar,
                                vectorNorm: vectorNorm),
                        mode: slot.mode,
                        concept: artifact.sidecar.concept))
            }
        }
        return injections
    }

    private func currentProbeSpecs() throws -> [ProbeSpec] {
        if let selectedReadingProbe {
            return [
                ProbeSpec(
                    layer: selectedReadingProbe.artifact.layer,
                    vector: nil,
                    vectorNorm: 0,
                    orientation: 1,
                    scalarProbe: selectedReadingProbe.artifact.probe,
                    label: selectedReadingProbe.label)
            ]
        }

        var specs: [ProbeSpec] = []
        for slot in slots where slot.enabled {
            guard let artifact = artifact(for: slot) else { continue }
            let conceptVectors = try conceptVectors(for: artifact)
            let center = min(
                max(0, artifact.fixedSteeringLayer ?? Int(slot.layer)),
                conceptVectors.layerCount - 1)
            let halfWidth = artifact.fixedSteeringLayer == nil
                ? max(0, (layerBandWidth - 1) / 2)
                : 0
            let lower = max(0, center - halfWidth)
            let upper = min(conceptVectors.layerCount - 1, center + halfWidth)
            for index in lower ... upper {
                let vector = projectedSteeringVector(conceptVectors.perLayer[index], layer: index)
                let vectorNorm = SteeringVectorMath.l2Norm(vector)
                guard vectorNorm > 0 else { continue }
                specs.append(
                    ProbeSpec(
                        layer: index,
                        vector: vector,
                        vectorNorm: vectorNorm,
                        orientation: slot.alpha < 0 ? -1 : 1,
                        scalarProbe: nil,
                        label: artifact.sidecar.concept))
            }
        }
        return specs
    }

    private func projectedSteeringVector(_ vector: [Float], layer: Int) -> [Float] {
        guard removeNeutralDirectionsAtSteering,
            let basis = selectedNeutralPCBasis?.basis
        else { return vector }
        let components = basis.components(for: layer)
        guard !components.isEmpty else { return vector }
        return SteeringVectorMath.projectingOut(vector, components: components)
    }

    private func probeScore(captures: [ActivationRecorder.Capture], specs: [ProbeSpec]) -> Float? {
        guard !captures.isEmpty, !specs.isEmpty else { return nil }
        let byLayer = Dictionary(grouping: specs, by: \.layer)
        var scores: [Float] = []
        for capture in captures {
            guard let layerSpecs = byLayer[capture.layer] else { continue }
            let activationNorm = SteeringVectorMath.l2Norm(capture.values)
            for spec in layerSpecs {
                if let scalarProbe = spec.scalarProbe {
                    if let score = try? scalarProbe.score(capture.values) {
                        scores.append(score)
                    }
                    continue
                }
                guard let vector = spec.vector, activationNorm > 0 else { continue }
                let dot = zip(capture.values, vector).reduce(Float(0)) {
                    $0 + $1.0 * $1.1
                }
                scores.append(spec.orientation * dot / (activationNorm * spec.vectorNorm))
            }
        }
        guard !scores.isEmpty else { return nil }
        return scores.reduce(0, +) / Float(scores.count)
    }

    private func probeScoresByOffset(
        captures: [ActivationRecorder.Capture], specs: [ProbeSpec]
    ) -> [Float] {
        guard !captures.isEmpty else { return [] }
        var scores: [Float] = []
        var currentOffset: Int?
        var group: [ActivationRecorder.Capture] = []

        func flush() {
            guard !group.isEmpty else { return }
            if let score = probeScore(captures: group, specs: specs) {
                scores.append(score)
            }
            group.removeAll(keepingCapacity: true)
        }

        for capture in captures {
            if currentOffset != capture.offset {
                flush()
                currentOffset = capture.offset
            }
            group.append(capture)
        }
        flush()
        return scores
    }

    private func probeHighlightOpacity(score: Float, calibrated: Bool) -> Double {
        let magnitude = Double(abs(score))
        let relative: Double
        if calibrated {
            // Scalar probes are z-ish after calibration; use a fixed curve so
            // one early spike cannot wash out the rest of the response.
            relative = tanh(magnitude / 2.0)
        } else {
            // Vector-cosine fallback is already bounded by [-1, 1].
            relative = min(1, magnitude)
        }
        guard relative >= 0.05 else { return 0 }
        return min(0.42, pow(relative, 0.9) * 0.42)
    }

    private func nilIfEmpty(_ text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? nil : trimmed
    }

    private func tokenCount(_ text: String, in container: ModelContainer) async -> Int {
        await container.perform { context in
            context.tokenizer.encode(text: text).count
        }
    }

    private func chatPrompt(_ prompt: String) -> String {
        guard selectedModelID.lowercased().contains("gemma"),
            let system = nilIfEmpty(systemPrompt)
        else { return prompt }
        return system + "\n\n" + prompt
    }

    /// (Re)creates the local ChatSession. With `replayingTranscriptUpTo` set,
    /// the first `count` transcript turns become the session's message
    /// history (mapped by the family adapter
    /// `ExperimentTasks.chatHistoryMessages`) and are re-rendered through the
    /// chat template on the next generation — how seeded assistant turns
    /// enter the model's context. Without it, a fresh empty session.
    private func startSession(replayingTranscriptUpTo count: Int? = nil) {
        pendingSeededHistoryReplay = false
        guard let container else { return }
        let isGemma = selectedModelID.lowercased().contains("gemma")
        let history: [Chat.Message]
        if let count, count > 0 {
            history = ExperimentTasks.chatHistoryMessages(
                turns: transcript.prefix(count).map {
                    ExperimentTasks.ChatTurn(
                        role: $0.role == .user ? .user : .assistant,
                        text: $0.text,
                        seeded: $0.isSeededOrContinued)
                },
                modelID: selectedModelID,
                systemPrompt: nilIfEmpty(systemPrompt))
        } else {
            history = []
        }
        // Studies default Qwen3 to no-think. The chat surface keeps the same
        // default but exposes a toggle for interactive comparison.
        session = ChatSession(
            container,
            instructions: isGemma ? nil : nilIfEmpty(systemPrompt),
            history: history,
            generateParameters: GenerateParameters(
                temperature: Float(temperature), prefillStepSize: 32768),
            additionalContext: ExperimentTasks.qwenContext(
                modelID: selectedModelID, qwenThinkingEnabled: qwenThinkingEnabled))
    }
