    /// Pure seam for the variant-seeding unit-mode announcement: applying a
    /// stored artifact adopts ITS explicit `alphaInNormUnits` flag (stored
    /// meaning rules — artifacts are never reinterpreted), so a flip away
    /// from the session's current mode must be visible, never silent — the
    /// same numeral means an order-of-magnitude different perturbation
    /// across modes. Returns the announcement line, or nil when the artifact
    /// leaves the mode unchanged.
    public nonisolated static func alphaUnitFlipAnnouncement(
        currentNormUnits: Bool, applying artifact: ModelVariantArtifact
    ) -> String? {
        guard artifact.alphaInNormUnits != currentNormUnits else { return nil }
        return artifact.alphaInNormUnits
            ? "variant '\(artifact.name)' uses residual-norm alphas "
                + "(α is a fraction of the layer's residual-stream norm)"
            : "variant '\(artifact.name)' uses raw alphas "
                + "(α values are literal α·v coefficients)"
    }

    private func applyModelVariantControls(_ record: ModelVariantRecord) {
        let artifact = record.artifact
        selectedModelID = artifact.baseModelID
        layerBandWidth = artifact.bandWidth
        let unitFlipNote = Self.alphaUnitFlipAnnouncement(
            currentNormUnits: alphaInNormUnits, applying: artifact)
        alphaInNormUnits = artifact.alphaInNormUnits
        promptMode = ExperimentManifest.PromptMode(rawValue: artifact.promptMode) ?? .chatAssistant
        qwenThinkingEnabled = artifact.qwenThinkingEnabled
        temperature = artifact.temperature
        if let systemPrompt = artifact.systemPrompt {
            self.systemPrompt = systemPrompt
        } else if artifact.systemPromptHash == nil {
            systemPrompt = ""
        }

        if let adapterRef = artifact.adapters.first,
            let adapter = fineTuning.adapters.first(where: { record in
                FineTuneStore.relativePath(for: record.url) == adapterRef.artifactPath
                    || record.artifact.adapterDirectory == adapterRef.adapterDirectory
            })
        {
            adaptersEnabled = true
            selectedRuntimeAdapterID = adapter.id
        } else {
            adaptersEnabled = false
            selectedRuntimeAdapterID = nil
        }

        if let basisPath = artifact.neutralPCBasisPath,
            let basis = neutralPCBases.first(where: {
                NeutralPCStore.relativePath(for: $0) == basisPath
                    || $0.label == artifact.neutralPCBasisLabel
            })
        {
            removeNeutralDirectionsAtSteering = true
            selectedNeutralPCBasisID = basis.id
        } else {
            removeNeutralDirectionsAtSteering = false
        }

        let restoredSlots = artifact.injections.compactMap { injection -> SteerSlot? in
            // Resolved, not literal: a server-promoted agent stores
            // `vectorArtifactID` workspace-relative while catalog ids are
            // absolute, so a literal compare made an imported agent VISIBLE
            // in the library (which resolves) and then silently unable to
            // restore its slots here (which did not). A partial fix is worse
            // than none — it moves the failure somewhere harder to see.
            guard vectors.contains(where: {
                ArtifactIdentity.canonical($0.id)
                    == ArtifactIdentity.canonical(injection.vectorArtifactID)
                    && $0.sidecar.modelID == artifact.baseModelID
            }) else { return nil }
            return SteerSlot(
                vectorID: injection.vectorArtifactID,
                layer: Double(injection.layer),
                alpha: injection.alpha,
                enabled: true)
        }
        slots = restoredSlots.isEmpty ? [SteerSlot()] : restoredSlots
        steeringEnabled = !restoredSlots.isEmpty
        resetChat()

        var notes: [String] = ["loaded variant '\(artifact.name)'"]
        if let unitFlipNote {
            notes.append(unitFlipNote)
        }
        if !artifact.adapters.isEmpty, selectedRuntimeAdapterID == nil {
            notes.append("adapter artifact not found")
        }
        let missingVectors = artifact.injections.count - restoredSlots.count
        if missingVectors > 0 {
            notes.append("\(missingVectors) vector\(missingVectors == 1 ? "" : "s") not found")
        }
        if artifact.systemPrompt == nil, artifact.systemPromptHash != nil {
            notes.append("older variant stores only a system-prompt hash")
        }
        errorMessage = notes.count > 1 ? notes.joined(separator: "; ") : nil
    }

    // MARK: Server-workspace variant seeding & inline composition

    /// Server-workspace parallel of `applyModelVariantToSteering`: selecting a
    /// stored server variant fetches its full spec (`GET /api/variant/detail`)
    /// and seeds the SAME live controls the local path populates — the stored
    /// variant is a seed for exploration, not a quarantine. An untouched seed
    /// sends the stored path + pinned hash; any edit composes an inline spec.
    public func applyRemoteVariantToSteering(path: String?) async {
        selectedRemoteVariantPath = path
        selectedRemoteVariantHash = nil
        // A stored server agent and a seeded local definition are mutually
        // exclusive selector identities.
        selectedServerLocalDefinitionID = nil
        seededServerControlState = nil
        lastServerVariantProvenance = nil
        guard let path, !path.isEmpty else { return }
        guard let client = cluster.client else {
            errorMessage = "invalid server URL"
            return
        }
        do {
            // The agent may reference vectors minted AFTER the last catalog
            // fetch (a just-promoted agent points at its sweep's artifacts) —
            // refresh first so the seeded rows resolve with real layer
            // bounds instead of falling back to name-only display.
            await catalog.refreshRemoteVectors()
            let detail = try await client.variantDetail(path: path)
            selectedRemoteVariantHash = detail.hash
            seedServerControls(from: detail.variant)
        } catch {
            // Older server without the detail route (or a transient failure):
            // stored-path sends still work — the controls just can't seed, so
            // dirty-tracking is off and sends keep exact stored provenance.
            errorMessage =
                "could not read the agent's spec (controls not seeded; sends "
                + "still use the stored agent): \(error)"
        }
    }

    /// Can this LOCAL variant definition be applied in the ACTIVE server
    /// workspace as an inline spec? Pure rule in
    /// `WorkspaceScoping.serverDefinitionApplicability`; this wrapper feeds it
    /// the live inventory/catalog: installed server models, the strict
    /// (`offerableForServerSteering`-filtered) vector catalog, and the server
    /// adapter listing matched by directory — the directory is what an inline
    /// spec sends, so a name-only match would not actually resolve.
    public func serverApplicability(
        of definition: ModelVariantArtifact
    ) -> WorkspaceScoping.DefinitionApplicability {
        WorkspaceScoping.serverDefinitionApplicability(
            definition: definition,
            installedModels: remoteModelOptions,
            resolveVectorConcept: { id in
                catalog.remoteVectors.first {
                    $0.id == id
                        && WorkspaceScoping.offerableForServerSteering(substrate: $0.substrate)
                }?.concept
            },
            resolveAdapter: { ref in
                serverAdapters.contains { $0.adapterDirectory == ref.adapterDirectory }
            })
    }

    /// Apply a LOCAL definition in the ACTIVE server workspace: seed the same
    /// live steering controls a stored server variant seeds — but as
    /// INLINE-composed state. No stored server path/hash is claimed (the
    /// server has no stored copy of this definition), so every send composes
    /// an inline spec the server stamps `source: "inline"`. Pre-flight: the
    /// definition must be fully applicable (base model installed, all vector
    /// refs in the catalog, adapter refs resolvable) — a partial application
    /// would silently steer with less than the definition says.
    public func applyLocalDefinitionToServerSteering(_ record: ModelVariantRecord) {
        guard isServerWorkspace else {
            applyModelVariantToSteering(record)
            return
        }
        let applicability = serverApplicability(of: record.artifact)
        if case .blocked(let reasons) = applicability {
            errorMessage =
                "cannot apply '\(record.artifact.name)' in this workspace: "
                + reasons.joined(separator: "; ")
            return
        }
        selectedRemoteVariantPath = nil
        selectedRemoteVariantHash = nil
        lastServerVariantProvenance = nil
        seedServerControls(from: record.artifact, sourceLabel: "local definition")
        // Selector identity LAST (seeding is what makes the claim true): the
        // Playground picker now shows this definition as selected — the Chat
        // handoff from the Agents tab previously loaded the settings while
        // the selector showed "None".
        selectedServerLocalDefinitionID = record.id
    }

    private func seedServerControls(
        from artifact: ModelVariantArtifact, sourceLabel: String = "server variant"
    ) {
        // The variant pins its base model, exactly like the local path.
        selectedRemoteModelID = artifact.baseModelID
        layerBandWidth = artifact.bandWidth
        let unitFlipNote = Self.alphaUnitFlipAnnouncement(
            currentNormUnits: alphaInNormUnits, applying: artifact)
        alphaInNormUnits = artifact.alphaInNormUnits
        promptMode = ExperimentManifest.PromptMode(rawValue: artifact.promptMode) ?? .chatAssistant
        qwenThinkingEnabled = artifact.qwenThinkingEnabled
        temperature = artifact.temperature
        if let systemPrompt = artifact.systemPrompt {
            self.systemPrompt = systemPrompt
        } else if artifact.systemPromptHash == nil {
            systemPrompt = ""
        }

        if let ref = artifact.adapters.first {
            adaptersEnabled = true
            seededServerAdapterRef = ref
            selectedServerAdapterID = ref.adapterDirectory
        } else {
            adaptersEnabled = false
            seededServerAdapterRef = nil
            selectedServerAdapterID = nil
        }

        serverNeutralPCBasisPath = artifact.neutralPCBasisPath
        serverNeutralPCBasisLabel = artifact.neutralPCBasisLabel

        serverSlotConceptFallback = Dictionary(
            artifact.injections.map { ($0.vectorArtifactID, $0.concept) },
            uniquingKeysWith: { first, _ in first })
        let restored = artifact.injections.map { injection in
            SteerSlot(
                vectorID: injection.vectorArtifactID,
                layer: Double(injection.layer),
                alpha: injection.alpha,
                enabled: true)
        }
        slots = restored.isEmpty ? [SteerSlot()] : restored
        steeringEnabled = !restored.isEmpty
        resetChat()

        var notes = ["loaded \(sourceLabel) '\(artifact.name)'"]
        if let unitFlipNote {
            notes.append(unitFlipNote)
        }
        let unresolved = restored.count { serverVectorRecord(for: $0) == nil }
        if unresolved > 0, !catalog.remoteVectors.isEmpty {
            notes.append(
                "\(unresolved) vector\(unresolved == 1 ? "" : "s") not in the "
                    + "server catalog listing (kept by path)")
        }
        // Multi-slot registry: the base model may be loaded in ANY slot, not
        // just the one `loadedModel` (singular) reports — the note previously
        // fired while the model was demonstrably serving chat (observed live).
        if !serverLoadedModelIDs.contains(artifact.baseModelID) {
            notes.append("load \(artifact.baseModelID) to apply its adapter and vectors")
        }
        errorMessage = notes.count > 1 ? notes.joined(separator: "; ") : nil
        // Snapshot AFTER populating: an immediate send counts as untouched.
        seededServerControlState = serverControlState()
    }

    /// The composed server control state PLUS the drop accounting: which
    /// enabled slots were excluded because their vector id did not resolve
    /// against the server catalog. Consumers must surface a non-empty
    /// `unresolvedVectorIDs` (send caption, error message, save refusal) —
    /// the user must never steer-and-not-know.
    public struct ServerControlResolution: Sendable {
        public let state: InlineVariantComposer.ControlState
        public let unresolvedVectorIDs: [String]
    }

    /// The current controls as the pure composer's snapshot, with honest
    /// accounting of dropped slots. Slots that don't resolve to a SERVER
    /// artifact (a local id left over from a workspace switch, a catalog
    /// listing that changed or failed to fetch) are excluded — a local
    /// vector path must never reach the server — but they are REPORTED, not
    /// swallowed; seeded-but-unlisted refs are kept via the concept fallback.
    public func serverControlResolution() -> ServerControlResolution {
        let resolution = InlineVariantComposer.resolveSlots(
            steeringEnabled: steeringEnabled,
            slots: slots.map {
                InlineVariantComposer.SlotInput(
                    vectorID: $0.vectorID, layer: Int($0.layer),
                    alpha: $0.alpha, enabled: $0.enabled, mode: $0.mode,
                    // Server-workspace ablations center by DECLARATION: the
                    // Mac never holds server vector bytes, so the toggle
                    // travels as `"centering": "neutralMean"` and the
                    // server's variant builder applies the artifact's stored
                    // mean (refusing loudly when the artifact has none).
                    centering: $0.mode == .ablate && centerAblationAgainstNeutralMean
                        ? "neutralMean" : nil)
            },
            concept: { serverConcept(forVectorID: $0) })
        return ServerControlResolution(
            state: composeControlState(slots: resolution.slots),
            unresolvedVectorIDs: resolution.unresolvedVectorIDs)
    }

    /// Convenience for callers that only need the composed state (seeding
    /// snapshots, disposition checks). Anything that ACTS on the state — a
    /// send, a save — should use `serverControlResolution()` and surface the
    /// dropped slots.
    public func serverControlState() -> InlineVariantComposer.ControlState {
        serverControlResolution().state
    }

    private func composeControlState(
        slots slotStates: [InlineVariantComposer.Slot]
    ) -> InlineVariantComposer.ControlState {
        var adapterRefs: [ModelVariantArtifact.AdapterRef] = []
        if adaptersEnabled, let selected = selectedServerAdapterID {
            if let seeded = seededServerAdapterRef, seeded.adapterDirectory == selected {
                adapterRefs = [seeded]
            } else {
                let record = serverAdapters.first { $0.id == selected }
                let name = record?.name ?? URL(filePath: selected).lastPathComponent
                // The catalog's sidecar vocabulary maps onto the AdapterRef
                // contract: bytes -> adapterHash, config -> configHash. Absent
                // stays absent (a legacy adapter is "unpinned", never
                // "verified"), but a server adapter that HAS them now pins
                // them instead of dropping them.
                adapterRefs = [
                    ModelVariantArtifact.AdapterRef(
                        name: name, artifactPath: selected,
                        adapterDirectory: selected,
                        adapterHash: record?.adapterBytesHash,
                        configHash: record?.adapterConfigHash)
                ]
            }
        }
        return InlineVariantComposer.ControlState(
            baseModelID: selectedRemoteModelID ?? "",
            slots: slotStates,
            adapters: adapterRefs,
            bandWidth: layerBandWidth,
            alphaInNormUnits: alphaInNormUnits,
            neutralPCBasisPath: serverNeutralPCBasisPath,
            neutralPCBasisLabel: serverNeutralPCBasisLabel,
            promptMode: promptMode.rawValue,
            qwenThinkingEnabled: qwenThinkingEnabled,
            temperature: temperature,
            systemPrompt: systemPrompt)
    }

    /// One-line live answer to "what will the next server send actually run?"
    /// — rendered under the variant picker so an edited seed visibly stops
    /// claiming the stored variant's identity before anything is sent.
    public var serverSendModeCaption: String {
        // The α denomination is standing state that changes what every alpha
        // numeral means — it lives in this persistent caption, not only in
        // the transient seeding banner (which is easy to miss).
        let denomination =
            steeringEnabled && !alphaInNormUnits
            ? " · RAW alphas (α·v literal — not residual-norm units)" : ""
        let resolution = serverControlResolution()
        // Dropped-slot warning is part of the PERSISTENT caption (not only a
        // transient errorMessage): while the condition holds, every glance at
        // the send-mode line says steering is being silently reduced.
        let unresolvedNote = InlineVariantComposer.unresolvedSlotCaption(
            count: resolution.unresolvedVectorIDs.count
        ).map { " · \($0)" } ?? ""
        switch InlineVariantComposer.disposition(
            storedVariantSelected: selectedRemoteVariantPath?.isEmpty == false,
            seeded: seededServerControlState,
            current: resolution.state)
        {
        case .storedVariant:
            // Unseedable spec + configured rows = the stored-variant shadow:
            // the standing caption must say the rows will NOT ride.
            let shadowNote = InlineVariantComposer.unseededStoredVariantWarning(
                storedVariantSelected: true,
                seeded: seededServerControlState != nil,
                configuredSlotCount: activeSlotCount
            ).map { " · ⚠︎ \($0)" } ?? ""
            return (seededServerControlState == nil
                ? "sends the stored agent by path (spec not seeded into the controls)"
                : "controls match the seeded agent — sends the stored agent "
                    + "(exact path + hash provenance)")
                + denomination + unresolvedNote + shadowNote
        case .inlineVariant:
            return "sends an inline spec composed from these controls "
                + "(server stamps source: \"inline\" — no stored-variant identity)"
                + denomination + unresolvedNote
        case .plainGenerate:
            return "no variant, no interventions — plain generation" + unresolvedNote
        }
    }

