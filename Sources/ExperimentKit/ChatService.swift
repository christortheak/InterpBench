    /// One steering slot — every slot is equal (no privileged "primary").
    /// The residual stream receives the SUM of all enabled slots:
    /// h ← h + Σ αᵢ·vᵢ — the injector list composes additively, so several
    /// slots ARE a linear combination. Negative alphas on a control concept
    /// (e.g. negative-valence) empirically cancel a shared component.
    public struct SteerSlot: Identifiable, Sendable {
        public let id: UUID
        public var vectorID: VectorArtifact.ID?
        public var layer: Double
        /// α when steering; λ when ablating. One field, because the control
        /// that edits it is swapped by the mode picker rather than shown
        /// alongside an irrelevant twin.
        public var alpha: Double
        public var enabled: Bool
        /// Steer (`h + α·v`) or ablate (`h − λ·(h·v̂)v̂`). Ablation ignores
        /// `layer`: it covers the whole network, because a single-layer
        /// removal is usually rewritten by the layers above it.
        public var mode: InterventionPlan.Mode

        /// A slot with no vector yet starts at ONE residual-stream norm, not
        /// the historical flat 2. Fresh sessions are in norm units, where 2 is
        /// two whole residual norms — off the end of the control's own −1…1
        /// range. As soon as a vector IS selected,
        /// `ChatService.applyDefaultsForSelectedVector` replaces this with
        /// what the artifact knows about itself (`SlotAlphaDefault`).
        public init(
            id: UUID = UUID(), vectorID: VectorArtifact.ID? = nil,
            layer: Double = 0, alpha: Double = SlotAlphaDefault.normUnitsDefault,
            enabled: Bool = true,
            mode: InterventionPlan.Mode = .add
        ) {
            self.id = id
            self.vectorID = vectorID
            self.layer = layer
            self.alpha = alpha
            self.enabled = enabled
            self.mode = mode
        }

        /// λ's default: full removal. Swapping modes should not carry a
        /// steering α over as a strength — α is typically 1–3, and λ = 2 is
        /// already a reflection rather than an ablation.
        public static let defaultAblationStrength: Double = 1
    }

    public struct InjectionPreview: Sendable {
        public let layer: Int
        public let vectorNorm: Float
        public let residualNorm: Float?
        public let effectiveAlpha: Float
        public let injectedNorm: Float
        public let isNormUnits: Bool
        /// True when the session is in norm units but this slot's denominator
        /// is missing/degenerate, so `effectiveAlpha` is the RAW α after all —
        /// the label must say so instead of claiming a norm-unit conversion.
        public let normUnitsFallback: Bool
        public let fixedLayer: Bool

        /// What this injection amounts to in residual-norm units, for RAW
        /// slots whose vector carries a denominator — the copy-this-number
        /// bridge for modernizing legacy raw-alpha variants (raw 6 ≈ 1.09
        /// norm units, say). Nil in norm-units mode (α already IS the units)
        /// and when no usable denominator exists.
        public var equivalentNormUnits: Float? {
            guard !isNormUnits, !normUnitsFallback,
                let residualNorm, residualNorm > 0
            else { return nil }
            return injectedNorm / residualNorm
        }

        /// The ONE preview computation, shared by the local and server slot
        /// paths so the Δnorm math cannot drift between substrates. Inputs are
        /// per-layer scalars: the vector's L2 norm at the injection layer
        /// (local: computed from the loaded — possibly neutral-projected —
        /// vector; server: the catalog's `normsPerLayer[layer]`) and the
        /// layer's typical residual norm when recorded. Norm-unit alphas
        /// convert via `SteeringVectorMath.normUnitScale` (injected L2 =
        /// α × residual norm); a missing/degenerate denominator falls back to
        /// raw α — matching what injection itself would do or refuse.
        public static func compute(
            layer: Int,
            vectorNorm: Float,
            residualNorm: Float?,
            alpha: Double,
            alphaInNormUnits: Bool,
            fixedLayer: Bool
        ) -> InjectionPreview? {
            guard vectorNorm > 0 else { return nil }
            var effectiveAlpha = Float(alpha)
            var normUnitsFallback = false
            if alphaInNormUnits {
                if let residualNorm,
                    let scaled = try? SteeringVectorMath.normUnitScale(
                        alpha: Float(alpha), residualNorm: residualNorm, vectorNorm: vectorNorm)
                {
                    effectiveAlpha = scaled
                } else {
                    // No usable denominator: the number shown IS the raw α.
                    // Flag it so the label can say so honestly.
                    normUnitsFallback = true
                }
            }
            return InjectionPreview(
                layer: layer,
                vectorNorm: vectorNorm,
                residualNorm: residualNorm,
                effectiveAlpha: effectiveAlpha,
                injectedNorm: abs(effectiveAlpha) * vectorNorm,
                isNormUnits: alphaInNormUnits,
                normUnitsFallback: normUnitsFallback,
                fixedLayer: fixedLayer)
        }
    }

    /// The steering boxes, in order. Always at least one.
    public var slots: [SteerSlot] = [SteerSlot()]
    /// Interpret alpha as a fraction of the layer's typical residual-stream
    /// norm (the emotion paper's units; requires a vector whose sidecar
    /// recorded residual norms). Raw alpha otherwise.
    ///
    /// Norm units are the DEFAULT for fresh sessions (decision of record:
    /// α as a proportion of the residual norm is the instrument's native
    /// denomination; raw is the explicitly-labeled fallback). Stored variant
    /// artifacts are never reinterpreted — seeding applies THEIR explicit
    /// flag, and a resulting mode flip is announced (see
    /// `alphaUnitFlipAnnouncement`). There is no silent downgrade to raw:
    /// sending with a norms-less vector still throws in `effectiveAlpha`.
    public var alphaInNormUnits = true
    /// Number of consecutive layers to inject (centered on `layer`, odd).
    public var layerBandWidth = 1

    /// The enabled rows whose alphas the norm-units denomination actually
    /// applies to. ABLATION rows are excluded: λ is a plain fraction of
    /// whatever is present in the residual stream and never consults a
    /// residual-norm denominator, so an ablate row on a norms-less vector
    /// (the routine case for J-lens/reader-derived directions) must neither
    /// gate the α-denomination toggle nor trip a norm-units refusal.
    nonisolated static func slotsRequiringNormDenominator(
        _ slots: [SteerSlot]
    ) -> [SteerSlot] {
        slots.filter { $0.enabled && $0.vectorID != nil && $0.mode != .ablate }
    }

    /// Norm units require every enabled STEERING slot's vector to have
    /// recorded residual norms — all steering alphas are interpreted in the
    /// same units (ablation λ never converts; see
    /// `slotsRequiringNormDenominator`). In a server workspace the conversion
    /// happens server-side from each vector's own sidecar
    /// (`variant_injections`); with the catalog now returning the real
    /// `residualNormPerLayer` arrays, the gate is per-slot layer coverage:
    /// the slot's (clamped) layer must have a usable denominator. Older
    /// catalogs without the arrays fall back to the `hasResidualNorms` flag —
    /// the honest disable stays only for vectors that genuinely lack residual
    /// norms (or aren't in the catalog at all).
    ///
    /// UI contract: `false` may only block turning norm units ON. Turning
    /// them OFF must always be possible — a blanket disable once locked the
    /// toggle ON for a norms-less vector (fresh sessions default to norm
    /// units), a dead end with no path to raw α (field report 2026-08-06).
    public var normUnitsAvailable: Bool {
        let steering = Self.slotsRequiringNormDenominator(slots)
        if isServerWorkspace {
            guard !steering.isEmpty else { return false }
            return steering.allSatisfy { slot in
                guard let record = serverVectorRecord(for: slot) else { return false }
                guard let norms = record.residualNormPerLayer else {
                    return record.hasResidualNorms == true
                }
                let layer = min(max(0, Int(slot.layer)), max(0, record.layerCount - 1))
                guard let norm = norms[safe: layer] else { return false }
                return norm > 0
            }
        }
        let active = steering.compactMap { artifact(for: $0) }
        return !active.isEmpty
            && active.allSatisfy { $0.sidecar.residualNormPerLayer != nil }
    }

