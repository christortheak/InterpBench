    /// Export label for a turn — seeded/edited provenance is part of the
    /// label so a researcher-authored (or researcher-altered) assistant turn
    /// is never indistinguishable from a real generation in any copied or
    /// saved record.
    nonisolated static func turnLabel(_ message: ChatMessage) -> String {
        switch message.role {
        case .user:
            return "User"
        case .assistant:
            if let prefixLength = message.seededPrefixLength {
                let revision = message.edited ? "; prefix edited from original" : ""
                return "Assistant (seeded prefix: first \(prefixLength) "
                    + "characters researcher-authored; rest generated\(revision))"
            }
            if let prefixLength = message.continuationPrefixLength {
                let prefix = message.edited ? "generated-then-edited" : "generated"
                return "Assistant (\(prefix) prefix: first \(prefixLength) "
                    + "characters; rest generated by continuation)"
            }
            if message.seeded, message.edited {
                // A continued turn (seeded prefix + generated tail) that was
                // edited afterwards — partially authored AND altered.
                return "Assistant (seeded, then edited by researcher — "
                    + "not a pure generation)"
            }
            if message.seeded {
                return "Assistant (seeded — researcher-authored, not generated)"
            }
            if message.edited {
                return "Assistant (generated, then edited by researcher)"
            }
            return "Assistant"
        }
    }

