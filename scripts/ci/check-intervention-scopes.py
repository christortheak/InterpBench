#!/usr/bin/env python3
"""Generate/check Swift scope prose from the Python vocabulary without GPU imports."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'Server/steerlab_server/steering/intervention.py'
TARGET = ROOT / 'Sources/SteeringKit/Injection/InterventionScopeVocabulary.swift'


def rendered():
    constants = []
    for node in ast.parse(SOURCE.read_text()).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                constants.append((node.targets[0].id, node.value.value))
    assert len(constants) >= 30, 'scope vocabulary was not found'
    lines = ['// Generated by scripts/ci/check-intervention-scopes.py --write. Do not edit.',
             'public enum InterventionScopeVocabulary {']
    lines.extend(f'    public static let {name} = {json.dumps(value, ensure_ascii=False)}' for name, value in constants)
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    expected = rendered()
    if args.write:
        TARGET.write_text(expected)
    if not TARGET.exists() or TARGET.read_text() != expected:
        raise SystemExit('Scope vocabulary differs; run scripts/ci/check-intervention-scopes.py --write')
    print('Intervention scope vocabulary matches Swift')


if __name__ == '__main__':
    main()
