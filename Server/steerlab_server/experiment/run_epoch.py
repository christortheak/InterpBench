"""Manifest-epoch stamps on run directories, and the guard that reads them.

A run directory records WHICH manifest epoch produced it, so a later verb can
refuse to treat a pre-edit run as evidence for a post-edit manifest. The stamp
lives in ``experiment-hash.txt`` with the canonical ``config.json``
``experimentHash`` as fallback.

Extracted from ``tasks.py`` (2026-07-26) so ``promote`` can apply the same
rule the evaluate/analyze guard already applied — a promotion that binds a
sweep run from a different manifest epoch mints an agent whose birth
certificate names settings that were selected under a different study.

The guard is deliberately per-engine: canonicalization differs between
substrates, so a run is checked on the engine that produced it.
"""

from __future__ import annotations

import json
import os

from . import manifest_diff
from ..steering.vector_store import SUBSTRATE


def stamped_experiment_hash(run_directory: str) -> str | None:
    """The run's manifest-epoch stamp, or None when absent/unreadable.

    ``experiment-hash.txt`` first, then the canonical ``config.json``
    ``experimentHash`` — the fallback for runs written before the dedicated
    file existed."""
    try:
        with open(os.path.join(run_directory, "experiment-hash.txt"),
                  encoding="utf-8") as handle:
            value = handle.read().strip()
        if value:
            return value
    except OSError:
        pass
    try:
        with open(os.path.join(run_directory, "config.json"),
                  encoding="utf-8") as handle:
            config = json.load(handle)
    except (OSError, json.JSONDecodeError, UnicodeDecodeError):
        return None
    if not isinstance(config, dict):
        return None
    value = config.get("experimentHash")
    return value if isinstance(value, str) and value else None


def snapshot(run_directory: str):
    """The manifest snapshot a run carries, decoded — the only epoch
    evidence that means the same thing on both engines."""
    from .manifest import Manifest
    try:
        with open(os.path.join(run_directory, "experiment.json"),
                  encoding="utf-8") as handle:
            return Manifest.from_dict(json.load(handle))
    except (OSError, json.JSONDecodeError, UnicodeDecodeError, KeyError,
            TypeError, ValueError):
        return None


def _without_self_projected(manifest, run_name: str):
    """A condition THIS run projected (``selection.sweepRun`` equals the
    run's own name) is the run's completion, not a different epoch: the
    sweep writes ``<concept>-recommended`` AFTER its start-time snapshot,
    and the Mac adopts the same projection into its local draft. Comparing
    epochs over those conditions made the guard refuse the exact state the
    run itself produced (field incident 2026-08-04). Cross-engine twin:
    ``RunEpoch.withoutSelfProjectedConditions``."""
    if manifest is None:
        return None
    from .manifest import Manifest, effective_study_type
    raw = dict(manifest.raw)
    conditions = raw.get("conditions") or []
    raw["conditions"] = [
        c for c in conditions
        if not (isinstance(c, dict)
                and (c.get("selection") or {}).get("sweepRun") == run_name)]
    # Presentation-classifier normalization (field incident 2026-08-04,
    # second refusal): the Studies panel stamps `studyType` on drafts when
    # the study is merely OPENED — absent and declared-as-derived mean the
    # same study, so both sides compare at the canonical value
    # (`effective_study_type`). A genuinely DIFFERENT declared type still
    # differs and still refuses.
    raw["studyType"] = effective_study_type(raw)
    try:
        return Manifest.from_dict(raw)
    except Exception:  # noqa: BLE001 - fall back to the unstripped manifest
        return manifest


#: Manifest fields that cannot affect a single generated byte of a source
#: run: they configure how existing generations are MEASURED (which judges,
#: which evaluation block) or how stages are CHAINED (the pipeline
#: declaration). The evaluate/analyze guards may tolerate drift confined to
#: these fields — loudly, and stamped into their output — because the
#: scientific object the guard protects (generations interpreted under the
#: settings that produced them) is untouched by them. Observed need
#: 2026-08-05: a study's pinned judge model died at its provider between run
#: and evaluate; swapping the judge changed the manifest hash and the guard
#: then demanded a full re-run to judge generations the edit could not have
#: affected. ``promote`` never tolerates: a judge swap changes what a
#: judged sweep's evidence means.
#:
#: The rubric pin and the human-validation pin joined 2026-08-05 (review of
#: the original tolerance): both are TOP-LEVEL keys read only at evaluate
#: time — a rubric is text handed to a judge, a humanValidation subset is
#: labels compared against verdicts — so a swap between run and evaluate
#: cannot have touched a generation. The motivating workflow is immediate:
#: re-pinning a study from the withdrawn paired K&Z rubric to the
#: perResponseCoding rubric must not demand a GPU re-run of a healthy
#: source run.
MEASUREMENT_FIELDS = ("judges", "evaluation", "pipeline",
                      "judgeRubricFile", "judgeRubricHash",
                      "humanValidation")

#: Keys a Swift struct round-trip materializes at their default even when the
#: donor's bytes never carried them (`experiment duplicate` decodes and
#: re-encodes, so every non-optional defaulted field appears). At the DEFAULT
#: the two spellings are the same manifest — the run behaved identically —
#: but ``content_hash`` is over raw JSON, where absent != false, so the
#: comparison canonicalizes default -> absent on BOTH sides before hashing.
#: Any other value is real generation-side drift and still refuses. The Swift
#: engine needs no twin: its comparison decodes both sides through the same
#: struct, materializing symmetrically. Observed 2026-08-28: a duplicate
#: refused against its donor's run over ``recordTokenIDs: false`` vs an
#: absent key — a difference with no meaning.
DEFAULT_VALUED_KEYS = {"recordTokenIDs": False}


def _without_measurement_fields(manifest):
    """The manifest reduced to its generation-side surface (top-level
    ``MEASUREMENT_FIELDS`` removed, ``name`` blanked) — the comparison
    object for the measurement-drift tolerance.

    ``name`` is blanked on BOTH sides, not listed in ``MEASUREMENT_FIELDS``:
    it is identity, not a measurement setting — but by the tolerance's own
    rule (a field that cannot have affected a byte of the source run's
    generations) a rename is tolerable on measurement verbs. Without this,
    the sanctioned duplicate-never-edit path (duplicate a study, pin a new
    rubric and panel, evaluate against the ORIGINAL run) refused on the one
    field the duplication itself must change (observed 2026-08-28, the
    calibration duplicate of a draft study). ``promote`` still refuses a
    renamed manifest: the tolerance only applies where
    ``tolerate_measurement_drift`` is passed. Swift twin:
    ``RunEpoch.withoutMeasurementFields``."""
    if manifest is None:
        return None
    from .manifest import Manifest
    raw = {k: v for k, v in manifest.raw.items()
           if k not in MEASUREMENT_FIELDS}
    raw["name"] = ""
    for key, default in DEFAULT_VALUED_KEYS.items():
        if raw.get(key) is default:
            del raw[key]
    try:
        return Manifest.from_dict(raw)
    except Exception:  # noqa: BLE001 - fall back to the strict comparison
        return manifest


def _with_snapshot_revision(live_cmp, snap):
    """The live manifest re-pinned with the run snapshot's model revision —
    or None when that repair does not apply.

    The run stage pins the resolved revision into a draft manifest
    (``_pin_model_revision``), but bundle re-imports overwrite the live file
    with the bundle's unpinned copy — so a run's snapshot can carry the
    pinned epoch while the live manifest is the same manifest one write
    behind its own machinery (observed 2026-08-05: a completed 2-hour
    pipeline refused its own continuation over exactly this). A live
    manifest that lacks a pin the snapshot has gets compared WITH that pin;
    a live manifest with a DIFFERENT pin is real drift and is not touched."""
    if live_cmp is None or snap is None:
        return None
    if getattr(live_cmp, "model_revision", None):
        return None
    revision = getattr(snap, "model_revision", None)
    if not revision:
        return None
    from .manifest import Manifest
    raw = dict(live_cmp.raw)
    raw["modelRevision"] = revision
    try:
        return Manifest.from_dict(raw)
    except Exception:  # noqa: BLE001 - fall back to the strict comparison
        return None


def _measurement_drift(live_cmp, snap) -> str | None:
    """The changed-fields description when live and snapshot differ ONLY in
    ``MEASUREMENT_FIELDS``, else None (the drift touches generation-side
    settings and must refuse)."""
    if live_cmp is None or snap is None:
        return None
    gen_live = _without_measurement_fields(live_cmp)
    gen_snap = _without_measurement_fields(snap)
    if gen_live is None or gen_snap is None:
        return None
    if gen_live.content_hash() != gen_snap.content_hash():
        return None
    drift = manifest_diff.changed_fields(live_cmp, snap)
    return drift.lstrip(": ") if drift else "measurement-side fields differ"


def unreadable_source_refusal(verb: str, run_directory: str) -> str | None:
    """The refusal for a source run that IS NOT THERE — ``None`` when the
    directory exists and can be read.

    **Why this is its own failure mode** (ledger 2026-08-21, live jobs
    47606365/47606373). A source run that cannot be opened produced no stamp,
    and the stamp reader cannot tell "unstamped" from "unreadable" — both
    answer ``None``. The guard therefore reported a correctly stamped run as
    one that "carries no experiment-hash stamp … or pass allowUnverifiedEpoch",
    which coaches the operator into disabling a scientific firewall gate to
    work around a PATH bug. The repair for this refusal is a path correction
    and nothing else, which is why the escape hatch is deliberately absent
    from its text: forgiving a missing stamp cannot make an absent directory
    readable.

    The message prints the RESOLVED absolute path, because the whole class of
    bug this separates out is "the relative path you typed was resolved
    against a directory you did not expect" — naming the string back at the
    operator is exactly what hid it.
    """
    resolved = os.path.abspath(run_directory)
    if os.path.isdir(resolved):
        if os.access(resolved, os.R_OK | os.X_OK):
            return None
        return (
            f"{verb}: the source run directory at {resolved} cannot be read "
            "(permissions) — nothing was read from it, so nothing is known "
            "about which manifest epoch it belongs to")
    if os.path.exists(resolved):
        return (
            f"{verb}: the source run path {resolved} is not a directory — a "
            "source run is the run DIRECTORY, not a file inside it")
    return (
        f"{verb}: the source run directory does not exist at {resolved} — a "
        "relative source path is resolved against the target root, not the "
        "working directory the job happens to start in. Nothing was read, so "
        "nothing is known about which manifest epoch it belongs to")


def unreadable_source_repair(verb: str, name: str) -> str:
    """The path-correction repair for :func:`unreadable_source_refusal`.

    Named separately so every surface says the same thing, and so no surface
    can accidentally offer the epoch escape for a path fault.
    """
    return (f"steerlab-server experiment {verb} {name} --source "
            "<runs/…-exp-…-run>  (a run directory that exists under the "
            "target root — `ls <root>/runs`; an absolute path always works, "
            "and a relative one is taken relative to the target root)")


def foreign_substrate_refusal(verb: str, run_name: str,
                              substrate: str) -> str:
    """The refusal a MEASUREMENT verb gives a run produced on the other
    engine. Byte-identical to Swift's
    ``RunEpoch.foreignSubstrateRefusal``; kept as its own composer so both
    engines' tests can assert the same sentence without a run directory."""
    return (
        f"{verb}: source run '{run_name}' was produced on {substrate}, and "
        f"{verb} reads that run's own records — record schemas and pairing "
        "keys are per-engine, so measuring them here reports an empty result "
        f"as a success. Run {verb} on the engine that produced the run")


def epoch_refusal(verb: str, name: str, live_hash: str, run_directory: str,
                  *, allow_unverified: bool, live_manifest=None,
                  tolerate_measurement_drift: bool = False,
                  refuse_foreign_substrate: bool = False
                  ) -> tuple[str | None, bool, str | None]:
    """Check a source run against the live manifest epoch.

    ``refuse_foreign_substrate`` separates the two families of caller, and it
    exists because the snapshot rescue below is right for one of them and
    wrong for the other (WP0 dry run #2's P0):

    - ``promote`` reads only the run's SELECTION metadata, which is
      engine-neutral JSON, and a cluster workspace's every sweep is foreign —
      so it must accept a foreign run whose manifest snapshot re-hashes to
      this engine's live hash. It passes False.
    - ``analyze``/``evaluate``/``rescore-style`` read the run's RECORDS,
      whose schema and pairing keys are per-engine (the server pairs on
      ``(promptID, sampleIndex)`` with a seed derived per condition, Swift on
      ``(seed, promptID)``) — so a foreign run read here silently produces no
      pairs and reports the empty result as a success. They pass True, and
      the snapshot rescue never gets to speak for them.

    Returns ``(refusal_or_None, unverified, measurement_drift)``.
    ``unverified`` is True when an unstamped legacy run was accepted under
    ``allow_unverified`` — the caller must then stamp ``epochUnverified:
    true`` into its own output. ``measurement_drift`` is the changed-fields
    description when a hash mismatch was accepted under
    ``tolerate_measurement_drift`` because every drifted field is
    measurement-side (``MEASUREMENT_FIELDS``) — the caller must log it and
    stamp it (``measurementDrift``) into its own output, the same loud-and-
    stamped pattern as ``epochUnverified``.

    Returning the refusal rather than raising keeps the error TYPE with the
    caller: ``tasks`` raises RuntimeError, ``promote`` raises PromoteError,
    and neither has to catch and re-wrap the other's."""
    run_name = os.path.basename(os.path.normpath(run_directory))
    # BEFORE anything else, including the foreign-substrate probe: a run that
    # cannot be opened at all is a PATH fault, not an epoch fact. Every reader
    # below (the stamp file, config.json, the manifest snapshot) answers None
    # for an absent directory, so without this the guard would go on to blame
    # the run's provenance for the operator's path — and offer the epoch
    # escape as the repair. See :func:`unreadable_source_refusal`.
    unreadable = unreadable_source_refusal(verb, run_directory)
    if unreadable is not None:
        return unreadable, False, None
    # FIRST, and before any stamp is read: a foreign run's stamp is not
    # comparable, and for a measurement verb the snapshot rescue below would
    # answer the wrong question — whether the SETTINGS match, when what fails
    # is reading the RECORDS. ``allow_unverified`` does not reach it either:
    # that flag forgives a missing stamp, not a substrate this engine cannot
    # read.
    if refuse_foreign_substrate:
        foreign = foreign_substrate(run_directory)
        if foreign is not None:
            return foreign_substrate_refusal(verb, run_name, foreign), \
                False, None
    stamped = stamped_experiment_hash(run_directory)
    if stamped is None:
        if allow_unverified:
            return None, True, None
        return (
            f"{verb}: source run '{run_name}' carries no experiment-hash "
            f"stamp, so it cannot be proven to belong to the current manifest "
            f"of '{name}' (hash {live_hash}) — re-run under the current "
            "manifest, or pass allowUnverifiedEpoch for legacy unstamped runs"
        ), False, None
    if stamped != live_hash:
        # Name the real cause when the run came from the OTHER engine. Epoch
        # hashes are per-engine by design (canonicalization differs), so a
        # foreign-substrate run ALWAYS mismatches — and blaming "a different
        # manifest epoch" sends the researcher hunting for a manifest change
        # that never happened. Twin of Swift's `RunEpoch.foreignSubstrate`.
        #
        # A foreign stamp is not evidence of a different epoch — it is no
        # evidence at all, because the hashes were never comparable. The run
        # carries its own manifest SNAPSHOT, so re-hash THAT with this
        # engine's function and compare like with like, the same pattern the
        # validate-evidence matcher uses. Without it, a workspace whose
        # evidence comes from the other engine can never promote or analyze
        # its own runs.
        foreign = foreign_substrate(run_directory)
        snap = _without_self_projected(snapshot(run_directory), run_name)
        live_cmp = _without_self_projected(live_manifest, run_name)
        live_cmp_hash = (live_cmp.content_hash() if live_cmp is not None
                         else live_hash)
        if foreign is not None:
            if snap is None:
                return (
                    f"{verb}: source run '{run_name}' was produced on "
                    f"{foreign} and carries no manifest snapshot, so there is "
                    f"no engine-neutral way to check it against '{name}' — "
                    "epoch stamps themselves do not cross substrates. Run "
                    f"{verb} on the engine that produced the run"
                ), False, None
            if snap.content_hash() == live_cmp_hash:
                return None, False, None
            repinned = _with_snapshot_revision(live_cmp, snap)
            if repinned is not None \
                    and snap.content_hash() == repinned.content_hash():
                # The run's own revision pin, clobbered from the live
                # manifest by a bundle re-import — same epoch, one write
                # behind (the self-projection precedent, revision form).
                return None, False, None
            if tolerate_measurement_drift:
                drift = _measurement_drift(live_cmp, snap)
                if drift is not None:
                    return None, False, drift
            return (
                f"{verb}: '{name}' has changed since source run '{run_name}' "
                "was produced"
                + manifest_diff.changed_fields(live_cmp, snap)
                + " — the run's settings are not the study's current settings"
            ), False, None
        if (snap is not None and live_cmp is not None
                and snap.content_hash() == live_cmp_hash):
            # Same-substrate self-projection tolerance: the hashes differ
            # only by conditions this run itself projected.
            return None, False, None
        repinned = _with_snapshot_revision(live_cmp, snap)
        if (snap is not None and repinned is not None
                and snap.content_hash() == repinned.content_hash()):
            # The run's own revision pin, clobbered from the live manifest
            # by a bundle re-import — same epoch, one write behind.
            return None, False, None
        if tolerate_measurement_drift:
            drift = _measurement_drift(live_cmp, snap)
            if drift is not None:
                return None, False, drift
        # No allowUnverifiedEpoch offer here: that flag is consulted only in
        # the unstamped branch above, and THIS run is stamped — offering it
        # on a stamped mismatch sent an agent back to burn a queue slot
        # learning it does nothing (observed 2026-08-28). The honest repairs
        # are the two that exist: re-run, or a measurement verb whose drift
        # is confined to the tolerated fields.
        return (
            f"{verb}: '{name}' has changed since source run '{run_name}' was "
            "produced" + manifest_diff.changed_fields(live_cmp, snap)
            + f" (run hash {stamped}, study now {live_hash}) — the run "
            "belongs to a different manifest epoch. Re-run under the current "
            "manifest; a measurement verb (evaluate/analyze/rescore-style) "
            "tolerates drift confined to measurement-side fields and stamps "
            "what it tolerated"
        ), False, None
    return None, False, None


def foreign_substrate(run_directory: str) -> str | None:
    """The run's recorded substrate when it differs from THIS engine's."""
    try:
        with open(os.path.join(run_directory, "config.json"),
                  encoding="utf-8") as handle:
            config = json.load(handle)
    except (OSError, json.JSONDecodeError, UnicodeDecodeError):
        return None
    if not isinstance(config, dict):
        return None
    substrate = config.get("substrate")
    if not isinstance(substrate, str) or substrate == SUBSTRATE:
        return None
    return substrate
