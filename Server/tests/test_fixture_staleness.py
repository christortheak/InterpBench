"""Every committed cross-engine fixture must still match the code that made it.

The fixtures are generated by THIS engine and consumed by the Swift suite, so
staleness is silent in the worst way: change a Python rule, forget to
regenerate, and Swift keeps passing against the old bytes while the two
engines diverge. Both suites stay green and the seam is broken — exactly the
failure the fixture strategy exists to prevent.

Three fixtures already had this check inline (scenario-diagnostics,
validation-layers, choice-margins). These are the four that did not, including
`server-minted-agent`, which is the one guarding the agent seam.
"""

import json
import os

import pytest

FIXTURES = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "Tests", "Fixtures", "cross-engine")

REGENERATE = ("stale fixture — re-run "
              "`Server/.venv.nosync/bin/python "
              "scripts/regenerate-cross-engine-fixtures.py` and commit")


def _load(name):
    path = os.path.join(FIXTURES, name)
    if not os.path.exists(path):
        pytest.skip(f"{name} not generated yet")
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def test_promotion_keys_fixture_is_current():
    from steerlab_server.experiment import promote

    cases = _load("promotion-keys.json")
    # Non-ASCII coverage must not shrink (2026-07-27): the canonical form is
    # raw UTF-8 (ensure_ascii=False), and only non-ASCII names can catch an
    # engine regressing to \uXXXX escaping — ASCII-only cases pass either way.
    assert sum(1 for case in cases
               if any(ord(ch) > 127
                      for ch in json.dumps(case["input"],
                                           ensure_ascii=False))) >= 3, \
        "the non-ASCII promotion-key coverage shrank"
    for case in cases:
        payload = case["input"]
        assert promote.promotion_key(
            experiment=payload["experiment"],
            experiment_hash=payload["experimentHash"],
            concept=payload["concept"],
            sweep_run=payload["sweepRun"],
            layer=payload["winningCell"]["layer"],
            alpha=payload["winningCell"]["alpha"],
            vector_artifact_id=payload["vectorArtifactID"],
            vector_artifact_hash=payload.get("vectorArtifactHash"),
            promoted_by=payload["promotedBy"],
            agent_name=payload["agentName"],
        ) == case["key"], f"{case['label']}: {REGENERATE}"


def test_scenario_row_hashes_fixture_is_current():
    from steerlab_server.experiment import scenario_diagnostics as sd

