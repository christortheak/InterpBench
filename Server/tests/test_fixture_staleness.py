def test_extraction_rendering_and_positions_fixture_is_current():
    """The rendering VOICE and the content-coordinate positions, re-derived.

    Stale bytes here would be the worst kind of silent: Swift would keep
    agreeing with an old canonicalization rule, and the two engines would
    disagree about what a recipe IS — which is a promotion that matches the
    wrong artifact, not a test failure.
    """
    from steerlab_server.experiment import recipe_identity as ri
    from steerlab_server.steering import extraction_rendering as er
    from steerlab_server.steering import reading_position as rp

    fixture = _load("extraction-rendering-and-positions.json")

    for entry in fixture["renderings"]:
        parsed = er.parse_declaration(entry["declaration"])
        stamp = parsed.to_dict() if parsed is not None else None
        assert stamp == entry["stamp"], f"{entry['label']}: {REGENERATE}"
        assert ri.rendering_fragment(parsed) == entry["identityFragment"], \
            f"{entry['label']}: {REGENERATE}"
        assert (parsed or er.RAW_RENDERING).label == entry["humanLabel"], \
            f"{entry['label']}: {REGENERATE}"

    assert fixture["refusals"] == {
        "assistantVoiceGenerationPrompt":
            er.ASSISTANT_VOICE_GENERATION_PROMPT_REASON,
        "assistantVoiceSystemPrompt":
            er.ASSISTANT_VOICE_SYSTEM_PROMPT_REASON,
        "unknownChatTemplateKey":
            er.unknown_chat_template_key_reason(["addGenerationPromt"]),
        "rawParameters":
            er.raw_parameters_reason(["addGenerationPrompt", "voice"]),
    }, REGENERATE
    assert fixture["chatTemplateKeys"] == list(er.CHAT_TEMPLATE_KEYS), REGENERATE

    for entry in fixture["positions"]:
        position = rp.parse_label_strict(entry["label"])
        assert position is not None, f"{entry['label']}: {REGENERATE}"
        mode, parameter = ri.canonical_reading(position)
        assert [position.identity_mode, position.identity_parameter,
                mode, parameter, position.minimum_token_count,
                position.requires_templated_rendering] == \
            [entry["identityMode"], entry["identityParameter"],
             entry["canonicalMode"], entry["canonicalParameter"],
             entry["minimumTokenCount"],
             entry["requiresTemplatedRendering"]], \
            f"{entry['label']}: {REGENERATE}"

    tokenizer = _FixtureTokenizer()
    tokens = fixture["tokens"]
    assert rp.content_indices(tokens, tokenizer, "fixture") == \
        fixture["contentIndices"], REGENERATE
    for entry in fixture["resolutions"]:
        resolved = rp.parse_label_strict(entry["label"]).resolve(
            tokens, tokenizer=tokenizer,
            rendering_is_raw=entry["renderingIsRaw"])
        assert [resolved.start_index, resolved.end_index, resolved.source,
                list(resolved.pooled_indices) if resolved.pooled_indices else None,
                resolved.masked_token_count, resolved.pooled_token_count] == \
            [entry["startIndex"], entry["endIndex"], entry["source"],
             entry["pooledIndices"], entry["maskedTokenCount"],
             entry["pooledTokenCount"]], f"{entry['label']}: {REGENERATE}"


class _FixtureTokenizer:
    """The generator's tokenizer, restated here so a drift in EITHER copy
    shows up as a failure rather than as two quietly matching mistakes."""

    eos_token_id = 106
    unk_token_id = 3
    _VOCAB = {"<bos>": 2, "<start_of_turn>": 105, "<end_of_turn>": 106,
              "\n": 107, "model": 108, "user": 109}
    _PIECES = {v: k for k, v in _VOCAB.items()}

    def convert_tokens_to_ids(self, token):
        return self._VOCAB.get(token, self.unk_token_id)

    def convert_ids_to_tokens(self, token_id):
        return self._PIECES.get(token_id, f"tok{token_id}")


def test_auto_prompt_ids_fixture_is_current(tmp_path):
    from steerlab_server.experiment import experiment_store as es, tasks
    from steerlab_server.experiment.manifest import Manifest

    fixture = _load("auto-prompt-ids.json")
    root = str(tmp_path)
    es.create("ids", model_id="org/m", root=root)
    path = os.path.join(root, "prompts.jsonl")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(fixture["lines"]) + "\n")
    prompts = tasks._load_prompts(Manifest.load("ids", root), path, root)
    assert [p["id"] for p in prompts] == fixture["ids"], REGENERATE


def test_server_minted_agent_fixture_is_current(tmp_path):
    """The one guarding the agent seam: if `save_variant` changes its layout
    or filename, Swift's discovery tests keep passing against the old shape
    while a real imported agent goes missing."""
    from steerlab_server.experiment import model_variant

    fixture = _load("server-minted-agent.json")
    artifact = fixture["artifact"]
    variant = model_variant.ModelVariant(
        name=artifact["name"],
        base_model_id=artifact["baseModelID"],
        base_revision=artifact.get("baseRevision"),
        injections=artifact.get("injections") or [],
        band_width=artifact.get("bandWidth", 1),
        alpha_in_norm_units=artifact.get("alphaInNormUnits", True),
        prompt_mode=artifact.get("promptMode", "chatAssistant"),
        qwen_thinking_enabled=artifact.get("qwenThinkingEnabled", False),
        temperature=artifact.get("temperature", 0.0),
        system_prompt=artifact.get("systemPrompt", ""),
        created_at=artifact.get("createdAt"),
        promotion=artifact.get("promotion"))
    saved = model_variant.save_variant(variant, str(tmp_path))

    basename = os.path.basename(saved["runDirectory"])
    stamp, _, _ = basename.partition("-")
    assert basename[len(stamp):] == fixture["runDirectorySuffix"], REGENERATE
    assert len(stamp) == fixture["runDirectoryStampLength"], REGENERATE
    assert os.path.basename(saved["path"]) == fixture["artifactFileName"], REGENERATE

    with open(os.path.join(saved["runDirectory"], "config.json"),
              encoding="utf-8") as handle:
        assert json.load(handle).get("runType") == fixture["configRunType"], \
            REGENERATE

    with open(saved["path"], encoding="utf-8") as handle:
        assert json.load(handle) == artifact, REGENERATE


def test_server_minted_adapter_agent_fixture_is_current(tmp_path):
    """The ADAPTER-entry seam (open-issues #11).

    The whole point of this fixture is that the server writes an adapter entry
    with NO `name` — Swift's decoder used to refuse the manifest over it. So
    the staleness check must pin two things: that `from_dict` → `save_variant`
    still round-trips the driver's dict VERBATIM, and that the committed bytes
    still lack the key. If the server ever starts minting a name, this fails
    and the Swift tolerance is reconsidered deliberately rather than left
    guarding a shape nothing produces."""
    from steerlab_server.experiment import model_variant

    fixture = _load("server-minted-adapter-agent.json")
    artifact = fixture["artifact"]

    entry = artifact["adapters"][0]
    assert "name" not in entry, (
        "the fixture no longer exercises the nameless adapter entry — "
        + REGENERATE)
    assert "artifactPath" not in entry, REGENERATE

    # The driver's POST body, rebuilt from the committed artifact minus the
    # keys `to_dict` adds, then re-saved through the real writer.
    body = {k: v for k, v in artifact.items() if k != "schemaVersion"}
    saved = model_variant.save_variant(
        model_variant.ModelVariant.from_dict(body), str(tmp_path))
    with open(saved["path"], encoding="utf-8") as handle:
        assert json.load(handle) == artifact, REGENERATE
    assert saved["hash"] == fixture["variantConditions"][0]["artifactHash"], \
        REGENERATE


def test_evidence_bundle_fixture_is_current():
    """The archive the Swift lifecycle test imports. Its bytes are a real
    `package_evidence` output, so a change to the packager — the manifest
    keys, the sibling-declaration rule, the layout — must not leave Swift
    importing a shape the server no longer writes."""
    fixture = _load("server-evidence-bundle.json")
    archive = os.path.join(FIXTURES, fixture["archive"])
    assert os.path.exists(archive), REGENERATE

    import hashlib
    with open(archive, "rb") as handle:
        digest = hashlib.sha256(handle.read()).hexdigest()
    assert digest == fixture["bundleSha256"], (
        "the committed archive does not match its recorded hash — " + REGENERATE)

    # The declaration the importer contracts on: siblings must be NAMED, not
    # merely packed. Bytes that travel undeclared are discarded on arrival.
    import tarfile
    with tarfile.open(archive) as tar:
        meta = json.load(tar.extractfile("steerlab-evidence.json"))
    declared = set(meta.get("pipelineStageDirectories") or [])
    assert fixture["sweepRun"] in declared, REGENERATE
    assert fixture["extractRun"] in declared, REGENERATE


def test_paired_difference_pca_fixture_is_not_stale():
    """The PCA path's numbers, re-derived.

    Stale bytes here would let the Swift engine keep agreeing with an old
    power-iteration — a different unit vector with the same norm and a
    plausible cosine, on artifacts nobody re-derives.
    """
    from steerlab_server.steering import vector_math as vm

    fixture = _load("paired-difference-pca.json")
    assert fixture["degenerateStartRelativeThreshold"] == \
        vm.DEGENERATE_START_RELATIVE_THRESHOLD, REGENERATE
    for case in fixture["principalComponents"]:
        assert vm.first_principal_component(case["rows"]) == \
            pytest.approx(case["firstPrincipalComponent"], abs=1e-6), \
            f"{case['label']}: {REGENERATE}"
    for case in fixture["directions"]:
        assert vm.mean_difference(case["positive"], case["negative"]) == \
            pytest.approx(case["meanDifference"], abs=1e-6), \
            f"{case['label']}: {REGENERATE}"
        assert vm.direction(
            case["positive"], case["negative"],
            vm.ExtractionMethod.PAIRED_DIFFERENCE_PCA) == \
            pytest.approx(case["pairedDifferencePCA"], abs=1e-6), \
            f"{case['label']}: {REGENERATE}"


def test_every_committed_fixture_has_a_staleness_test():
    """A new fixture with no staleness check is the gap this file closes, so
    adding one must not silently reopen it."""
    covered = {
        "promotion-keys.json", "scenario-row-hashes.json",
        "auto-prompt-ids.json", "server-minted-agent.json",
        "extraction-rendering-and-positions.json",
        "paired-difference-pca.json",
        "server-minted-adapter-agent.json",
        # Checked inline in their own suites.
        "scenario-diagnostics.json", "validation-layers.json",
        "validation-depth-lists.json",
        "choice-margins.json", "server-evidence-bundle.json",
        # Checked inline in test_system_prompt_composition.py.
        "system-prompt-composition.json",
        # Phase-0 portability contracts. The two produced by THIS engine are
        # write-if-missing goldens checked inline in
        # test_portability_contracts.py (delete the file and re-run that
        # module to regenerate). The third is produced by the SWIFT engine
        # (Tests/ExperimentKitTests/PortabilityContractTests.swift), so its
        # staleness check lives there, on the side that can rebuild it.
        "manifest-interop.json", "run-bundle-metadata.json",
        "swift-authored-manifest.json",
    }
    present = {f for f in os.listdir(FIXTURES) if f.endswith(".json")}
    assert present <= covered, (
        "these fixtures have no staleness test: "
        + ", ".join(sorted(present - covered)))
