import Foundation
import Testing

@testable import ExperimentKit
import SteeringKit

/// What a panel seat passes on (public issue #15), on the Mac engine: the
/// shared splitter against its Python twin's fixture, and the pure pieces the
/// run loop composes — turn reading, routed text, contract own-inputs,
/// endpoint parsing, seat effort and temperature, and the resume rule.
@Suite("ReasoningSplitTests")
struct ReasoningSplitTests {
    // Written by hand: the reasoning tries "Final answer: affirm" out, and
    // the answer gives "reverse".
    static let avaText =
        "I first lean one way. Final answer: affirm? No — the record shows the "
        + "error was not harmless.\n</think>\n\nFinal answer: reverse. The error "
        + "was not harmless."
    static let avaReasoning =
        "I first lean one way. Final answer: affirm? No — the record shows the "
        + "error was not harmless.\n"
    static let avaAnswer = "Final answer: reverse. The error was not harmless."

    // MARK: - Cross-engine fixture

    /// The splitter, the turn reading, and the own-reasoning framing must be
    /// byte-identical across engines. Generated by the Python engine —
    /// regenerate with `scripts/regenerate-cross-engine-fixtures.py`.
    @Test func splitterMatchesThePythonTwin() throws {
        let url = CodeResources.compiledCheckoutPath.appending(
            components: "Tests", "Fixtures", "cross-engine", "reasoning-split.json")
        let fixture = try #require(
            try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any])
        let splits = try #require(fixture["split"] as? [[String: Any]])
        #expect(splits.count >= 12)
        for entry in splits {
            let label = try #require(entry["label"] as? String)
            let found = ReasoningSplit.split(try #require(entry["text"] as? String))
            #expect(found.reasoning == entry["reasoning"] as? String, "\(label)")
            #expect(found.answer == entry["answer"] as? String, "\(label)")
            #expect(found.state.rawValue == entry["state"] as? String, "\(label)")
        }
        let turns = try #require(fixture["turnText"] as? [[String: Any]])
        for entry in turns {
            let label = try #require(entry["label"] as? String)
            let said = MultiAgentRunner.turnText(
                try #require(entry["text"] as? String),
                thinking: try #require(entry["thinking"] as? Bool),
                finishReason: entry["finishReason"] as? String)
            #expect(said.answer == entry["answer"] as? String, "\(label)")
            #expect(said.reasoning == entry["reasoning"] as? String, "\(label)")
            #expect(said.status?.rawValue == entry["status"] as? String, "\(label)")
        }
        let own = try #require(fixture["ownReasoning"] as? [[String: Any]])
        for entry in own {
            let label = try #require(entry["label"] as? String)
            #expect(
                MultiAgentRunner.ownReasoningText(
                    reasoning: try #require(entry["reasoning"] as? String),
                    answer: try #require(entry["answer"] as? String))
                    == entry["text"] as? String, "\(label)")
        }
    }

    @Test func theJudgeStillStripsEachShape() {
        let body = "{\"winner\": \"A\"}"
        #expect(PairedJudgeVerdictParser.strippingLeadingThinkBlock("<think>x</think>" + body) == body)
        #expect(PairedJudgeVerdictParser.strippingLeadingThinkBlock("x</think>" + body) == body)
        #expect(PairedJudgeVerdictParser.strippingLeadingThinkBlock(body) == body)
        #expect(
            PairedJudgeVerdictParser.strippingLeadingThinkBlock("<think>deliberating " + body)
                == "deliberating " + body)
    }

    // MARK: - What a colleague reads

    static func panel(includeOwnReasoning: Bool? = nil) -> MultiAgentScenario {
        MultiAgentScenario(
            name: "p", baseModelID: "m",
            agents: [
                .init(id: "a", name: "Ava", baseModelID: "m"),
                .init(id: "b", name: "Ben", baseModelID: "m"),
            ],
            turns: [
                .init(
                    id: "t1", title: "Ava votes", speakerAgentID: "a",
                    promptTemplate: "Vote.", outputLabel: "ava1", routing: .all,
                    endpoint: try? JSONDecoder().decode(
                        TurnEndpoint.self,
                        from: Data(
                            #"{"name":"vote","kind":"choice","marker":"Final answer:","vocabulary":["affirm","reverse"]}"#
                                .utf8))),
                .init(
                    id: "t2", title: "Ben reads", speakerAgentID: "b",
                    promptTemplate: "Ava said: {{outputs.ava1}}", outputLabel: "ben1"),
                .init(
                    id: "t3", title: "Ava again", speakerAgentID: "a",
                    promptTemplate: "Again.", outputLabel: "ava2",
                    contract: TurnContract(task: "Vote again.", inputs: ["ava1"])),
            ],
            includeOwnReasoning: includeOwnReasoning)
    }

    @Test(arguments: [false, true])
    func aColleagueReadsOnlyTheAnswerAndTheSpeakerFollowsTheSetting(_ own: Bool) throws {
        let scenario = Self.panel(includeOwnReasoning: own)
        let said = MultiAgentRunner.turnText(Self.avaText, thinking: true, finishReason: "stop")
        #expect(said.answer == Self.avaAnswer)
        #expect(said.reasoning == Self.avaReasoning)
        let ava = scenario.agents[0]
        let turn = scenario.turns[0]
        // Ben's routed entry and his template both carry the answer alone.
        let benEntry = MultiAgentRunner.contextEntry(
            turn: turn, outputLabel: "ava1", speaker: ava,
            output: MultiAgentRunner.routedText(scenario: scenario, said: said, own: false),
            reader: "b")
        let benPrompt = MultiAgentRunner.renderPrompt(
            scenario: scenario, turn: scenario.turns[1], speakerName: "Ben",
            speakerContext: benEntry, outputsByLabel: ["ava1": said.answer],
            reasoningByLabel: ["ava1": Self.avaReasoning])
        #expect(benPrompt.contains(Self.avaAnswer))
        #expect(!benPrompt.contains("affirm"))
        #expect(!benPrompt.contains("I first lean"))
        // Ava's own entry, and her contract's own-authored input, follow the
        // panel's setting.
        let avaEntry = MultiAgentRunner.contextEntry(
            turn: turn, outputLabel: "ava1", speaker: ava,
            output: MultiAgentRunner.routedText(scenario: scenario, said: said, own: true),
            reader: "a")
        let avaPrompt = MultiAgentRunner.renderPrompt(
            scenario: scenario, turn: scenario.turns[2], speakerName: "Ava",
            speakerContext: avaEntry, outputsByLabel: ["ava1": said.answer],
            reasoningByLabel: ["ava1": Self.avaReasoning])
        let withReasoning = MultiAgentRunner.ownReasoningText(
            reasoning: Self.avaReasoning, answer: Self.avaAnswer)
        if own {
            #expect(avaEntry.contains(withReasoning))
            #expect(avaPrompt.contains(withReasoning))
        } else {
            #expect(!avaEntry.contains("I first lean"))
            #expect(!avaPrompt.contains("I first lean"))
            #expect(avaPrompt.contains(Self.avaAnswer))
        }
        // The endpoint is the answer's, and says the reasoning tried one out.
        let stamp = try #require(
            MultiAgentRunner.endpointStamp(
                for: turn, output: said.answer, reasoning: said.reasoning))
        #expect(stamp.value == .choice("reverse"))
        #expect(stamp.markerInReasoning == true)
        let encoded = String(decoding: try JSONEncoder().encode(stamp), as: UTF8.self)
        #expect(encoded.contains("\"markerInReasoning\":true"))
        let plain = try #require(MultiAgentRunner.endpointStamp(for: turn, output: said.answer))
        #expect(
            !String(decoding: try JSONEncoder().encode(plain), as: UTF8.self)
                .contains("markerInReasoning"))
    }

    @Test func aSeatThatDoesNotThinkIsNeverSplit() {
        let text = "<think>not a real block</think> but my words"
        let said = MultiAgentRunner.turnText(text, thinking: false, finishReason: "stop")
        #expect(said == MultiAgentRunner.TurnText(answer: text))
        #expect(said.passedOn)
    }

    @Test func reasoningThatNeverClosedPassesNothingOn() {
        for (text, finish) in [
            ("<think>weighing affirm", "stop"),
            ("weighing affirm", "lengthInReasoning"),
            ("weighing affirm", "length"),
        ] {
            let said = MultiAgentRunner.turnText(text, thinking: true, finishReason: finish)
            #expect(said.status == .cutOff)
            #expect(!said.passedOn)
            #expect(said.answer.isEmpty)
        }
    }

    // MARK: - Seat effort and temperature

    @Test func aBareSeatFollowsTheStudysEffortAndAnAgentKeepsItsOwn() throws {
        let directory = FileManager.default.temporaryDirectory
            .appending(component: "steerlab-fr6a-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let artifact = ModelVariantArtifact(
            name: "thinker", baseModelID: "m", promptMode: "chatAssistant",
            qwenThinkingEnabled: true, temperature: 0.9, systemPrompt: "")
        let path = directory.appending(component: "thinker.json")
        try JSONEncoder().encode(artifact).write(to: path)

        let bare = MultiAgentScenario.Agent(id: "b", name: "Ben", baseModelID: "m")
        let bareOn = try MultiAgentRunner.seatReasoning(
            for: bare, studyEffort: .on, studyBudget: 300)
        #expect(bareOn.effort == .on && bareOn.budget == 300)
        let bareOff = try MultiAgentRunner.seatReasoning(
            for: bare, studyEffort: .off, studyBudget: nil)
        #expect(bareOff.effort == .off && bareOff.budget == nil)

        let agent = MultiAgentScenario.Agent(
            id: "a", name: "Ava", baseModelID: "m", variantArtifactPath: path.path)
        let thinking = try MultiAgentRunner.seatReasoning(
            for: agent, studyEffort: .off, studyBudget: 300)
        #expect(thinking.effort == .xhigh && thinking.budget == 300)
    }

    @Test func aSeatRunsAtItsDeclaredTemperatureAndSaysWhereItCameFrom() {
        let own = MultiAgentScenario.Agent(id: "a", name: "Ava", baseModelID: "m", temperature: 0.8)
        let plain = MultiAgentScenario.Agent(id: "b", name: "Ben", baseModelID: "m")
        #expect(MultiAgentRunner.seatTemperature(own, studyTemperature: 0, studyOwned: true) == (0.8, "panelSeat"))
        #expect(MultiAgentRunner.seatTemperature(plain, studyTemperature: 0.3, studyOwned: true) == (0.3, "study"))
        #expect(MultiAgentRunner.seatTemperature(plain, studyTemperature: 0.3, studyOwned: false) == (0.3, "panel"))
    }

    @Test func seatTemperatureRoundTripsAndIsValidated() throws {
        var scenario = Self.panel(includeOwnReasoning: true)
        scenario.agents[1].temperature = 0.6
        let data = try JSONEncoder().encode(scenario)
        let text = String(decoding: data, as: UTF8.self)
        #expect(text.contains("\"temperature\":0.6"))
        #expect(text.contains("\"includeOwnReasoning\":true"))
        let decoded = try JSONDecoder().decode(MultiAgentScenario.self, from: data)
        #expect(decoded.agents[1].temperature == 0.6 && decoded.showsOwnReasoning)

        // Absent stays absent: a panel from before the keys keeps its bytes.
        let before = Self.panel()
        let plain = String(decoding: try JSONEncoder().encode(before), as: UTF8.self)
        #expect(!plain.contains("includeOwnReasoning"))
        #expect(!plain.contains("\"temperature\":0.6"))
        var off = before
        off.includeOwnReasoning = false
        #expect(off.includeOwnReasoning == nil)
        let sorted = JSONEncoder()
        sorted.outputFormatting = [.sortedKeys]
        #expect(try sorted.encode(off) == sorted.encode(before))

        scenario.agents[1].temperature = -0.5
        #expect(throws: ExperimentError.self) { try MultiAgentRunner.validate(scenario) }
        #expect(
            MultiAgentRunner.seatTemperatureProblem(scenario.agents[1])
                == "seat 'Ben' declares temperature -0.5; a seat's temperature must be 0 "
                + "or more (0 is greedy), or left out to use the study's temperature")
        // A string is not a temperature.
        let bad = Data(
            #"{"id":"a","name":"Ava","baseModelID":"m","systemPrompt":"","temperature":"0.6"}"#.utf8)
        #expect(throws: DecodingError.self) {
            try JSONDecoder().decode(MultiAgentScenario.Agent.self, from: bad)
        }
    }

    @Test func verifyNamesASeatTemperatureThatEqualsTheStudys() {
        var scenario = Self.panel()
        scenario.agents[1].temperature = 0.7
        #expect(
            MultiAgentRunner.seatTemperatureAdvisories(scenario, studyTemperature: 0.7) == [
                "seat 'Ben' declares temperature 0.7, which is the study's temperature, so "
                    + "the declaration changes nothing. Remove it from the panel, or give the "
                    + "seat the different temperature you meant."
            ])
        #expect(MultiAgentRunner.seatTemperatureAdvisories(scenario, studyTemperature: 0.2).isEmpty)
    }

    // MARK: - Resume never mixes two routing rules

    static func oldEngineTurn(speaker: String) -> MultiAgentTurnResult {
        MultiAgentTurnResult(
            turnID: "t1", turnIndex: 1, title: "Ava votes", speakerAgentID: speaker,
            speakerName: "Ava", modelRevision: nil, prompt: "Vote.", output: avaText,
            outputLabel: "ava1", routedAgentIDs: ["a", "b"])
    }

    @Test func aTranscriptAnOlderEngineStartedResumesOnlyWhereTheRuleChangesNothing() throws {
        let scenario = Self.panel()
        // A bare seat under a study that does not think: nothing changes.
        #expect(
            MultiAgentRunner.resumeRuleRefusal(
                scenario: scenario, completed: ["t1": Self.oldEngineTurn(speaker: "a")],
                studyEffort: .off) == nil)
        // The same seat under a thinking study now thinks: refused.
        let refusal = try #require(
            MultiAgentRunner.resumeRuleRefusal(
                scenario: scenario, completed: ["t1": Self.oldEngineTurn(speaker: "a")],
                studyEffort: .on))
        #expect(refusal.reason.contains("seat 'Ava' thinks"))
        #expect(refusal.lifecycleRefusal?.gate == .manifestEpoch)
        // A turn this engine wrote carries its effort, and resumes.
        var current = Self.oldEngineTurn(speaker: "a")
        current.reasoningEffort = "on"
        #expect(
            MultiAgentRunner.resumeRuleRefusal(
                scenario: scenario, completed: ["t1": current], studyEffort: .on) == nil)
    }
}
