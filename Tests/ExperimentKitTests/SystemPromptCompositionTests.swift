    @Test func emptyPersonaPlusFrameIsExactlyTodaysFrameOnlyValue() {
        // THE regression lock (hard constraint of the ruling). Every real run
        // in the workspace today has an empty persona on every arm; its
        // records stamp sha256(frame). Composition must not move that by a
        // byte, or every historical run's stamp starts describing a prompt
        // that was never rendered.
        for empty in [nil, "", "   "] as [String?] {
            let composed = SystemPromptComposition.compose(
                agent: empty, frame: Self.frame)
            #expect(composed == Self.frame)
            #expect(SystemPromptComposition.hash(composed) == sha(Self.frame))
        }
        #expect(SystemPromptComposition.hash(nil) == nil)
        #expect(SystemPromptComposition.hash("") == nil)
    }

    /// Review 2026-08-26. `compose` classified `"   "` as empty on both
    /// levels, but only the AGENT side's emptiness reached a nil: the frame
    /// shortcut returned the whitespace survivor, so `compose(" ", nil)` was
    /// nil and `compose(nil, " ")` was `" "` — one arm with a null effective
    /// hash, one with a digest of a blank, from two contributions the rule
    /// calls equally empty and both stamps call `null`. Argument order is not
    /// allowed to decide effective identity. Server twin:
    /// `test_two_empty_levels_compose_to_none_whichever_side_the_blank_is_on`.
    @Test func twoEmptyLevelsComposeToNilWhicheverSideTheBlankIsOn() {
        let blank = "   \n\t "
        let pairs: [(String?, String?)] = [
            (blank, nil), (nil, blank), (blank, blank), (blank, ""),
            ("", blank), ("", ""), (nil, nil),
        ]
        for (agent, frame) in pairs {
            let composed = SystemPromptComposition.compose(
                agent: agent, frame: frame)
            #expect(composed == nil)
            #expect(SystemPromptComposition.hash(composed) == nil)
            let arm = ArmSystemPrompt(agent: agent, study: frame)
            #expect(arm.effective == nil)
            #expect(arm.stamp == .none)
            let seat = SeatSystemPrompt(agent: agent, cast: frame)
            #expect(seat.effective == nil)
            #expect(seat.stamp.agent == nil)
            #expect(seat.stamp.cast == nil)
        }
        // The canonicalization reaches ONLY the both-empty case: a survivor
        // with content in it comes back byte-identical, as it always has.
        let survivor = "  a frame with edges  "
        #expect(SystemPromptComposition.compose(agent: blank, frame: survivor)
            == survivor)
        #expect(SystemPromptComposition.compose(agent: survivor, frame: blank)
            == survivor)
    }

    @Test func theCompositionStampAlwaysEncodesBothKeys() throws {
        // Explicit nulls: an ABSENT key would read as "this engine does not
        // stamp composition", a different claim from "this level was empty".
        // The server always writes both, so this engine must too.
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        let bare = SystemPromptCompositionStamp(
            agentText: nil, studyText: Self.frame)
        let json = try #require(
            String(data: try encoder.encode(bare), encoding: .utf8))
        #expect(json == #"{"agent":null,"study":"\#(sha(Self.frame))"}"#)

        let battery = BatteryArmingCompositionStamp(
            agentText: nil, batteryText: nil)
        #expect(
            String(data: try encoder.encode(battery), encoding: .utf8)
                == #"{"agent":null,"battery":null}"#)
    }

    /// Review 2026-08-26. `compose` treats whitespace-only text as empty, but
    /// the stamp used to hash by TRUTHINESS — so a persona of `"   "`
    /// contributed nothing to the effective prompt and still stamped a digest,
    /// claiming a contribution the bytes do not contain. All three stamp
    /// shapes, both levels.
    @Test func aLevelTheCompositionDropsStampsNullInAllThreeShapes() {
        let blank = "   \n\t "
        // The effective prompt is the OTHER side's exact bytes…
        #expect(SystemPromptComposition.compose(agent: blank, frame: Self.frame)
            == Self.frame)
        #expect(SystemPromptComposition.compose(agent: Self.persona, frame: blank)
            == Self.persona)

        // …so the dropped level stamps null, wherever the stamp is built.
        let study = SystemPromptCompositionStamp(
            agentText: blank, studyText: Self.frame)
        #expect(study.agent == nil)
        #expect(study.study == sha(Self.frame))
        let battery = BatteryArmingCompositionStamp(
            agentText: Self.persona, batteryText: blank)
        #expect(battery.agent == sha(Self.persona))
        #expect(battery.battery == nil)
        let cast = PanelSystemPromptCompositionStamp(
            agentText: blank, castText: Self.frame)
        #expect(cast.agent == nil)
        #expect(cast.cast == sha(Self.frame))
        // …and through the two arming types that build text and stamp together.
        let arm = ArmSystemPrompt(agent: blank, study: Self.frame)
        #expect(arm.effective == Self.frame)
        #expect(arm.stamp.agent == nil)
        let seat = SeatSystemPrompt(agent: Self.persona, cast: blank)
        #expect(seat.effective == Self.persona)
        #expect(seat.stamp.cast == nil)

        // The per-condition hash convention is UNTOUCHED: one convention,
        // shared with the server's `_sha256_text`. The composition rule lives
        // at the stamp and nowhere else.
        #expect(SystemPromptComposition.hash(blank) == sha(blank))
        #expect(SystemPromptComposition.stampHash(blank) == nil)
        #expect(SystemPromptComposition.stampHash(Self.frame) == sha(Self.frame))
    }

    @Test func armSystemPromptBuildsTheTextAndTheStampTogether() {
