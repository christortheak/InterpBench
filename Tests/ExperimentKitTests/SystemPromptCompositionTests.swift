/// System-prompt COMPOSITION (maintainer ruling, 2026-08-24) — Swift half.
///
/// Before this, the two system-prompt levels REPLACED one another: a
/// baseline/steering arm ran under the study's `manifest.systemPrompt` (the
/// deployment frame), while a variant/agent arm ran under the agent
/// artifact's `systemPrompt` with the frame simply not applied. The frame was
/// therefore part of the contrast rather than held constant, and promotion
/// made it worse by copying the frame onto every newborn agent.
///
/// The contract-defining engine is the Python one; the cross-engine fixture
/// consumed at the bottom of this file is generated by it
/// (`scripts/regenerate-cross-engine-fixtures.py`), so a rule change on one
/// side cannot pass unnoticed on the other. Server twin:
/// `Server/tests/test_system_prompt_composition.py`.
struct SystemPromptCompositionTests {

    private static let frame = "You are a federal district judge. Respond in JSON."
    private static let persona = "You are Adjudicator-7, cautious and terse."

    private func sha(_ text: String) -> String {
        SHA256.hash(data: Data(text.utf8))
            .map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - The composition rule

    @Test func theAgentPersonaComesFirstJoinedByOneBlankLine() {
        // Identity precedes instruction: the frame's "answer in this format"
        // is an instruction TO whoever the model is being.
        #expect(
            SystemPromptComposition.compose(
                agent: Self.persona, frame: Self.frame)
                == Self.persona + "\n\n" + Self.frame)
        #expect(SystemPromptComposition.joiner == "\n\n")
    }

    @Test(arguments: [
        (Self.persona, Self.frame, Self.persona + "\n\n" + Self.frame),
        (nil, Self.frame, Self.frame),
        ("", Self.frame, Self.frame),
        ("   ", Self.frame, Self.frame),
        (Self.persona, nil, Self.persona),
        (Self.persona, "", Self.persona),
        (Self.persona, "  \n ", Self.persona),
        (nil, nil, nil),
        ("", "", ""),
    ] as [(String?, String?, String?)])
    func compositionDegradesGracefullyInEveryDirection(
        agent: String?, frame: String?, expected: String?
    ) {
        #expect(SystemPromptComposition.compose(agent: agent, frame: frame)
            == expected)
    }

    @Test func emptyPersonaPlusFrameIsExactlyTodaysFrameOnlyValue() {
        // THE regression lock (hard constraint of the ruling). Every real run
        // in the workspace today has an empty persona on every arm; its
        // records stamp sha256(frame). Composition must not move that by a
        // byte, or every historical run's stamp starts describing a prompt
        // that was never rendered.
        for empty in [nil, "", "   "] as [String?] {
            let composed = SystemPromptComposition.compose(
                agent: empty, frame: Self.frame)
            #expect(composed == Self.frame)
            #expect(SystemPromptComposition.hash(composed) == sha(Self.frame))
        }
        #expect(SystemPromptComposition.hash(nil) == nil)
        #expect(SystemPromptComposition.hash("") == nil)
    }

    @Test func theCompositionStampAlwaysEncodesBothKeys() throws {
        // Explicit nulls: an ABSENT key would read as "this engine does not
        // stamp composition", a different claim from "this level was empty".
        // The server always writes both, so this engine must too.
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        let bare = SystemPromptCompositionStamp(
            agentText: nil, studyText: Self.frame)
        let json = try #require(
            String(data: try encoder.encode(bare), encoding: .utf8))
        #expect(json == #"{"agent":null,"study":"\#(sha(Self.frame))"}"#)

        let battery = BatteryArmingCompositionStamp(
            agentText: nil, batteryText: nil)
        #expect(
            String(data: try encoder.encode(battery), encoding: .utf8)
                == #"{"agent":null,"battery":null}"#)
    }

    @Test func armSystemPromptBuildsTheTextAndTheStampTogether() {
        let arm = ArmSystemPrompt(agent: Self.persona, study: Self.frame)
        #expect(arm.effective == Self.persona + "\n\n" + Self.frame)
        #expect(arm.stamp.agent == sha(Self.persona))
        #expect(arm.stamp.study == sha(Self.frame))

        let bare = ArmSystemPrompt(agent: nil, study: Self.frame)
        #expect(bare.effective == Self.frame)
        #expect(bare.stamp.agent == nil)
    }

    // MARK: - The comparability advisory

    @Test func identicalArmsEmitNothing() {
        // The universal current case must stay silent, or the advisory is
        // noise nobody reads.
        #expect(
            SystemPromptComposition.divergenceAdvisory(arms: [
                ("baseline", Self.frame), ("agent-x", Self.frame),
            ]) == nil)
        #expect(
            SystemPromptComposition.divergenceAdvisory(arms: [
                ("baseline", nil), ("agent-x", nil),
            ]) == nil)
        #expect(
            SystemPromptComposition.divergenceAdvisory(
                arms: [("baseline", Self.frame)]) == nil)
    }

    @Test func divergentArmsAreNamedWithTheirHashes() throws {
        let composed = SystemPromptComposition.compose(
            agent: Self.persona, frame: Self.frame)
        let advisory = try #require(
            SystemPromptComposition.divergenceAdvisory(arms: [
                ("baseline", Self.frame), ("adjudicator", composed),
            ]))
        #expect(advisory.contains("baseline (" + sha(Self.frame).prefix(12)))
        #expect(
            advisory.contains(
                "adjudicator (" + (SystemPromptComposition.hash(composed) ?? "")
                    .prefix(12)))
        #expect(advisory.contains("Not a refusal."))
    }

    @Test func anArmWithNoSystemContentIsNamedNone() throws {
        let advisory = try #require(
            SystemPromptComposition.divergenceAdvisory(arms: [
                ("bare", nil), ("framed", Self.frame),
            ]))
        #expect(advisory.contains("bare (none)"))
    }

    // MARK: - Battery isolation

    private func battery(_ lines: String..., file: String = "b.jsonl") throws
        -> CapabilityBattery
    {
        try CapabilityBattery(
            data: Data(lines.joined(separator: "\n").utf8), file: file)
    }

    private var choiceItem: String {
        #"{"id":"cap-1","prompt":"Capital of France?","answer":"Paris",""#
            + #"options":["Paris","Rome","Berlin"]}"#
    }

    @Test func aFormatTwoBatteryTakesThePersonaAndNeverTheStudyFrame() throws {
        // The agent IS the model under test, so its identity belongs in a
        // capability reading; the study's deployment frame is the context of
        // the study's own task and is exactly what produced the
        // 0.45-vs-1.00 split format 2 exists to end.
        let loaded = try battery(
            #"{"batteryFormat":2,"maxTokens":8,"systemPrompt":"Answer plainly."}"#,
            choiceItem)
        let agentArm = loaded.resolveArming(
            promptMode: .rawCompletion, systemPrompt: Self.frame,
            qwenThinkingEnabled: true, agentSystemPrompt: Self.persona)
        #expect(agentArm.systemPrompt == Self.persona + "\n\nAnswer plainly.")
        #expect(agentArm.systemPrompt?.contains(Self.frame) == false)
        #expect(agentArm.agentSystemPrompt == Self.persona)
        #expect(agentArm.declaredSystemPrompt == "Answer plainly.")
    }

    @Test func theBaselineArmReadsTheBatteryBare() throws {
        let loaded = try battery(
            #"{"batteryFormat":2,"maxTokens":8,"systemPrompt":"Answer plainly."}"#,
            choiceItem)
        // No agent ⇒ the battery's own arming ALONE, whatever the study frame
        // is. That is what makes baseline the control for the agent arms.
        let baseline = loaded.resolveArming(
            promptMode: .chatAssistant, systemPrompt: Self.frame)
        #expect(baseline.systemPrompt == "Answer plainly.")
        #expect(baseline.agentSystemPrompt == nil)
    }

    @Test func aFormatOneBatteryIgnoresTheAgentChannelEntirely() throws {
        // Legacy arming IS the surrounding instrument's, defect included, so
        // its pinned hash keeps its historical meaning. The new channel must
        // not reach it.
        let legacy = try battery(
            #"{"prompt":"What is the capital of France?","answer":"paris","grading":"token_exact"}"#)
        let arming = legacy.resolveArming(
            promptMode: .chatAssistant, systemPrompt: Self.frame,
            qwenThinkingEnabled: false, agentSystemPrompt: Self.persona)
        #expect(arming.systemPrompt == Self.frame)
        #expect(arming.agentSystemPrompt == nil)
        #expect(arming.declaredSystemPrompt == nil)
        #expect(!arming.isolated)
    }

    @Test func batteryRowsStampTheirArmingCompositionAdditively() throws {
        let loaded = try battery(
            #"{"batteryFormat":2,"maxTokens":8,"systemPrompt":"Answer plainly."}"#,
            choiceItem)
        let arming = loaded.resolveArming(agentSystemPrompt: Self.persona)
        let record = ExperimentTasks.batteryRecord(
            condition: "agent-x", promptIndex: 1, item: loaded.items[0],
            score: .init(
                scoring: .choiceProbability, options: ["Paris", "Rome"],
                choiceProbability: ["Paris": 0.8, "Rome": 0.2],
                selected: "Paris", output: "Paris", correct: true),
            battery: loaded, arming: arming)
        // The four historical arming keys are untouched — this is ADDITIVE.
        #expect(record.armingIsolated == true)
        #expect(record.armingPromptMode == "chatAssistant")
        #expect(record.armingSystemPrompt == true)
        #expect(record.armingMaxTokens == 8)
        #expect(
            record.armingSystemPromptHash
                == .some(sha(Self.persona + "\n\nAnswer plainly.")))
        #expect(
            record.armingSystemPromptComposition
                == BatteryArmingCompositionStamp(
                    agent: sha(Self.persona), battery: sha("Answer plainly.")))
    }

    @Test func aFormatOneRowKeepsItsExactHistoricalKeySet() throws {
        let legacy = try battery(
            #"{"prompt":"What is the capital of France?","answer":"Paris","grading":"token_exact"}"#)
        let arming = legacy.resolveArming(systemPrompt: Self.frame)
        let record = ExperimentTasks.batteryRecord(
            condition: "baseline", promptIndex: 1, item: legacy.items[0],
            score: .init(
                scoring: .generatedText, options: nil, choiceProbability: nil,
                selected: nil, output: "Paris", correct: true),
            battery: legacy, arming: arming)
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        let object = try #require(
            try JSONSerialization.jsonObject(with: try encoder.encode(record))
                as? [String: Any])
        #expect(
            Set(object.keys) == [
                "condition", "promptIndex", "prompt", "expected", "output",
                "correct",
            ])
    }

    // MARK: - Record stamps

    @Test func aStudyRecordAlwaysCarriesItsCompositionStamp() throws {
        var manifest = ExperimentManifest(
            name: "s", description: "", modelID: "org/m")
        manifest.systemPrompt = Self.frame
        let arm = ArmSystemPrompt(agent: Self.persona, study: Self.frame)
        let record = ExperimentTasks.sampledGenerationRecord(
            manifest: manifest, experimentHash: String(repeating: "a", count: 64),
            taskPromptsFile: "prompts/tasks/items.jsonl",
            taskPromptsHash: String(repeating: "b", count: 64),
            promptMode: .chatAssistant,
            systemPrompt: arm.effective,
            systemPromptComposition: arm.stamp,
            qwenThinkingEnabled: false, condition: "agent-x", seed: 0,
            promptIndex: 1,
            prompt: .init(
                id: "p0", text: "Decide the case.", options: nil, target: nil,
                anchorMonths: nil, severity: nil, arm: nil, caseID: nil),
            output: "an answer",
            row: .init(
                condition: "agent-x", seed: 0, promptIndex: 1, promptID: "p0",
                wordCount: 2, distinct2: 1, markerDensity: [:]))
        #expect(record.systemPrompt == Self.persona + "\n\n" + Self.frame)
        #expect(record.systemPromptComposition.agent == sha(Self.persona))
        #expect(record.systemPromptComposition.study == sha(Self.frame))

        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        let object = try #require(
            try JSONSerialization.jsonObject(with: try encoder.encode(record))
                as? [String: Any])
        let stamp = try #require(
            object["systemPromptComposition"] as? [String: Any])
        #expect(stamp.keys.sorted() == ["agent", "study"])
    }

    // MARK: - Promotion no longer inherits

    private func withTempWorkspace<T>(_ body: (URL) throws -> T) rethrows -> T {
        let temp = FileManager.default.temporaryDirectory
            .appending(component: "sysprompt-\(UUID().uuidString)")
        try? FileManager.default.createDirectory(
            at: temp, withIntermediateDirectories: true)
        ExperimentRootOverrideLock.acquire()
        WorkspaceRoot.programmaticOverride = temp
        defer {
            WorkspaceRoot.programmaticOverride = nil
            ExperimentRootOverrideLock.release()
            try? FileManager.default.removeItem(at: temp)
        }
        return try body(temp)
    }

    private static let fearHash = String(repeating: "f", count: 64)

    private func plantVectorArtifact(in root: URL) throws {
        let runDir = root.appending(
            components: "runs", "20260707T000001000-extract")
        try FileManager.default.createDirectory(
            at: runDir, withIntermediateDirectories: true)
        try Data("weights".utf8).write(
            to: runDir.appending(component: "fear.safetensors"))
        let sidecar: [String: Any] = [
            "modelID": "test/model", "concept": "fear",
            "stimulusSetHash": Self.fearHash, "layerCount": 4, "hiddenSize": 2,
            "normsPerLayer": [1.0, 1.0, 1.0, 1.0],
            "residualNormPerLayer": [1.0, 1.0, 1.0, 1.0],
            "extractionDate": "2026-07-07T00:00:00Z",
            "extractionMethod": "meanDifference", "substrate": "swift-mlx",
            "revision": "abc123", "readingPosition": "last token",
            "neutralProjection": "none",
            "residualNormSource": "extraction-stimuli",
        ]
        try JSONSerialization.data(withJSONObject: sidecar)
            .write(to: runDir.appending(component: "fear.json"))
    }

    private func plantSweepRun(in root: URL, experiment name: String) throws
        -> String
    {
        let runName = "20260726T000000000-exp-\(name)-sweep"
        let runDir = root.appending(components: "runs", runName)
        try FileManager.default.createDirectory(
            at: runDir, withIntermediateDirectories: true)
        try Data(
            "concept,layer,alpha,markerDensity,distinct2,batteryAccuracy\n".utf8
        ).write(to: runDir.appending(component: "sweep.csv"))
        let entry: [String: Any] = [
            "sweepRun": runName,
            "criterion": [
                "objective": ["metric": "markerDensity"],
                "constraints": [
                    "capabilityTolerance": 0.15, "coherenceFloor": 0.45,
                ],
            ],
            "devPromptsHash": String(repeating: "d", count: 64),
            "winningCell": ["layer": 3, "alpha": 0.4],
            "metrics": ["markerDensity": 0.31],
        ]
        try JSONSerialization.data(withJSONObject: ["fear": entry])
            .write(to: runDir.appending(component: "recommendations.json"))
        try Data(
            ExperimentStore.manifestHash(try ExperimentStore.load(name: name))
                .utf8
        ).write(to: runDir.appending(component: "experiment-hash.txt"))
        return runName
    }

    @Test func promotionGivesANewbornAgentNoSystemPromptAtAll() throws {
        // Pre-fix this copied `manifest.systemPrompt` onto the agent, so the
        // study's deployment frame travelled with it into the next study —
        // where, under composition, it would be concatenated with that
        // study's own frame: the same text twice in one system turn.
        try withTempWorkspace { root in
            var manifest = try ExperimentStore.create(
                name: "promo", description: "", modelID: "test/model",
                modelRevision: "abc123")
            manifest.concepts.append(
                .init(name: "fear", stimulusSetHash: Self.fearHash,
                      options: .init()))
            manifest.systemPrompt = Self.frame
            try ExperimentStore.save(manifest)
            try plantVectorArtifact(in: root)
            let run = try plantSweepRun(in: root, experiment: "promo")

            let record = try AgentPromotion.promote(
                experimentName: "promo", concept: "fear",
                pins: .init(sweepRun: run), log: { _ in })

            #expect(record.artifact.systemPrompt == nil)
            #expect(record.artifact.systemPromptHash == nil)
            // …and a later study composing this agent gets that study's frame
            // alone, not two frames.
            #expect(
                SystemPromptComposition.compose(
                    agent: record.artifact.systemPrompt, frame: "another frame")
                    == "another frame")
        }
    }

    // MARK: - Validation stays frame-free

    @Test func theStudyFrameNeverReachesAHeldOutValidationRead() throws {
        // A probe score is a projection onto the extracted direction. If a
        // run-time deployment frame changed the rendering, the held-out
        // accuracy would move with a deployment choice rather than with the
        // vector. Structurally, validation reads ONE channel — the concept's
        // own `resolvedExtractionRendering` — which has no access to the
        // manifest at all; this pins that the channel stays independent.
        var manifest = ExperimentManifest(
            name: "v", description: "", modelID: "org/m")
        manifest.systemPrompt = Self.frame
        manifest.concepts.append(
            .init(name: "fear", stimulusSetHash: Self.fearHash,
                  options: .init()))
        let undeclared = manifest.concepts[0].options.resolvedExtractionRendering
        #expect(undeclared.systemPrompt == nil)

        // The SANCTIONED channel, and it does reach the read: it is part of
        // recipe identity, so extraction and validation cannot silently
        // disagree about it.
        let pinned = "You are describing a scene."
        manifest.concepts[0].options.extractionRendering =
            ExtractionRendering.chatTemplate(systemPrompt: pinned)
        let declared = manifest.concepts[0].options.resolvedExtractionRendering
        #expect(declared.systemPrompt == pinned)

        // Changing the study frame changes nothing about either rendering.
        manifest.systemPrompt = "a completely different frame"
        #expect(
            manifest.concepts[0].options.resolvedExtractionRendering.systemPrompt
                == pinned)
    }

    // MARK: - Cross-engine fixture

    /// The composition rule, its stamps, and the advisory's exact wording must
    /// be byte-identical across engines: two runs of the same study on two
    /// substrates would otherwise be two different studies. These expectations
    /// are generated by the Python engine — regenerate with
    /// `scripts/regenerate-cross-engine-fixtures.py`.
    @Test func compositionMatchesThePythonTwin() throws {
        let fixtureURL = CodeResources.compiledCheckoutPath
            .appending(
                components: "Tests", "Fixtures", "cross-engine",
                "system-prompt-composition.json")
        let data = try Data(contentsOf: fixtureURL)
        let fixture = try #require(
            try JSONSerialization.jsonObject(with: data) as? [String: Any])
        #expect(fixture["joiner"] as? String == SystemPromptComposition.joiner)

        let cases = try #require(fixture["composition"] as? [[String: Any]])
        #expect(cases.count >= 10)
        for entry in cases {
            let label = try #require(entry["label"] as? String)
            let agent = entry["agent"] as? String
            let study = entry["study"] as? String
            let effective = SystemPromptComposition.compose(
                agent: agent, frame: study)
            #expect(effective == entry["effective"] as? String, "\(label)")
            #expect(
                SystemPromptComposition.hash(effective)
                    == entry["effectiveHash"] as? String, "\(label)")
            let studyStamp = try #require(entry["studyStamp"] as? [String: Any])
            let mine = SystemPromptCompositionStamp(
                agentText: agent, studyText: study)
            #expect(mine.agent == studyStamp["agent"] as? String, "\(label)")
            #expect(mine.study == studyStamp["study"] as? String, "\(label)")
            let batteryStamp = try #require(
                entry["batteryStamp"] as? [String: Any])
            let mineBattery = BatteryArmingCompositionStamp(
                agentText: agent, batteryText: study)
            #expect(
                mineBattery.agent == batteryStamp["agent"] as? String, "\(label)")
            #expect(
                mineBattery.battery == batteryStamp["battery"] as? String,
                "\(label)")
        }

        let advisories = try #require(fixture["advisories"] as? [[String: Any]])
        #expect(advisories.count >= 4)
        for entry in advisories {
            let label = try #require(entry["label"] as? String)
            let arms = try #require(entry["arms"] as? [[String: Any]]).map {
                (name: ($0["name"] as? String) ?? "",
                 systemPrompt: $0["systemPrompt"] as? String)
            }
            #expect(
                SystemPromptComposition.divergenceAdvisory(arms: arms)
                    == entry["advisory"] as? String, "\(label)")
        }
    }
